package generate

import (
	"fmt"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

// EstateName is the file the module map of an estate is written to, beside
// the modules' own documents.
const EstateName = "estate.md"

// EstateModule is one module an estate lists, as the module map shows it.
type EstateModule struct {
	Key      string
	Location string     // as the estate writes it
	Version  string     // the version the estate lists
	About    string     // the estate's description of it
	RelRoot  string     // its root file from the document's folder; "" when it was not found
	Root     *yaml.Node // its specification; nil when it was not found or did not parse
}

// Estate writes the module map of an estate (ADR-113): the modules with
// the version each is held at, and the references between them through
// their dependencies, drawn as the context diagram. marks are the estate's
// own problems, each shown at its module.
func Estate(root *yaml.Node, relEstate string, modules []EstateModule, marks []Mark) string {
	d := &doc{}
	info := get(root, "info")
	d.line("<!-- Generated by specarch document techspec from %s, version %s; estate format %s. Do not edit this file: change the YAML and generate again. -->", relEstate, str(info, "version"), str(root, "specarchEstate"))
	d.blank()
	d.line("# %s: module map", str(info, "title"))
	d.blank()
	d.para(fmt.Sprintf("Version %s of the estate: %s. Each module is specified on its own; this map lists them, the version the estate holds each at, and what each names in another through its dependencies.", str(info, "version"), countText(len(modules), "module", "modules")))
	if desc := str(info, "description"); desc != "" {
		d.para(desc)
	}
	if len(marks) > 0 {
		d.para(fmt.Sprintf("**Problems:** %s the estate; each is shown below the modules, at its entry, and specarch validate prints them.", countText(len(marks), "problem concerns", "problems concern")))
	}

	known := map[string]bool{}
	for _, m := range modules {
		known[m.Key] = true
	}
	d.line("## Modules")
	d.blank()
	d.line("| Module | Held at | Specification | What it is |")
	d.line("|---|---|---|---|")
	for _, m := range modules {
		spec := "not found at " + m.Location
		what := ""
		if m.RelRoot != "" {
			spec = fmt.Sprintf("[%s](%s)", m.Location, m.RelRoot)
		}
		if m.Root != nil {
			mi := get(m.Root, "info")
			what = str(mi, "title")
			if v := str(mi, "version"); v != m.Version {
				what += fmt.Sprintf(" (its specification is at %s)", v)
			}
		}
		if m.About != "" {
			what = strings.TrimSpace(strings.TrimSuffix(what, ".") + ". " + m.About)
			what = strings.TrimPrefix(what, ". ")
		}
		d.line("| %s | %s | %s | %s |", m.Key, m.Version, spec, cell(what))
	}
	d.blank()
	for _, mk := range marks {
		d.para(fmt.Sprintf("**Problem** at %s (%s:%d): %s", mk.Pointer, mk.File, mk.Line, mk.Message))
	}

	type edge struct{ from, dep, to, version string }
	var edges []edge
	outside := map[string]bool{}
	for _, m := range modules {
		for _, dp := range pairs(m.Root, "dependencies") {
			to := str(dp.Value, "specification")
			if to == "" {
				continue
			}
			edges = append(edges, edge{m.Key, dp.Key.Value, to, str(dp.Value, "version")})
			if !known[to] {
				outside[to] = true
			}
		}
	}
	d.line("## References between modules")
	d.blank()
	if len(edges) == 0 {
		d.para("No module names another through a dependency.")
		return d.String()
	}
	var b strings.Builder
	b.WriteString("flowchart LR\n")
	for _, m := range modules {
		label := m.Key + " " + m.Version
		if m.Root != nil {
			label = str(get(m.Root, "info"), "title") + " (" + label + ")"
		}
		fmt.Fprintf(&b, "  %s[\"%s\"]\n", mermaidID(m.Key), mermaidText(label))
	}
	var others []string
	for o := range outside {
		others = append(others, o)
	}
	sort.Strings(others)
	for _, o := range others {
		fmt.Fprintf(&b, "  %s[/\"%s, not in the estate\"/]\n", mermaidID(o), mermaidText(o))
	}
	for _, e := range edges {
		fmt.Fprintf(&b, "  %s -->|\"%s\"| %s\n", mermaidID(e.from), mermaidText(e.dep+", written against "+e.version), mermaidID(e.to))
	}
	d.WriteString(fence(b.String()))
	d.blank()
	d.line("| Module | Dependency | Specification it names | Written against |")
	d.line("|---|---|---|---|")
	for _, e := range edges {
		to := e.to
		if !known[to] {
			to += " (not in the estate)"
		}
		d.line("| %s | %s | %s | %s |", e.from, e.dep, to, e.version)
	}
	d.blank()
	return d.String()
}
