// Package gendxlib writes the Go of a service on dxlib from a
// specification: the logic of the specarch-gen-go-dxlib plug-in. It writes
// one file with what a dxlib service otherwise declares by hand: a table per
// entity, a handler per operation registered by its operationId with a
// typed accessor for its parameters and the checks dxlib's validator does
// not make, the privileges, roles and menu items as data, and a task per
// job. The parameter names are the dxlib dialect's (genopenapi.Wire), so
// the handlers and the document dxlib binds agree by construction. The
// schema is not declared here: specarch-gen-sql writes it.
package gendxlib

import (
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/SpecArch/specarch/internal/genopenapi"
	"github.com/SpecArch/specarch/internal/ownership"
)

// FileName is the file the plug-in writes in the target's folder.
const FileName = "specarch_dxlib.go"

// Generate writes the Go of a request.
func Generate(r *genopenapi.Request) genopenapi.Response {
	g := &gen{spec: r.Specification, root: r.Root, imports: map[string]bool{}, owned: ownership.Owned{}}
	for _, impl := range r.Implementations {
		for ptr, by := range ownership.Of(impl.Content) {
			g.owned[ptr] = by
		}
		if s := impl.Settings; s != nil && g.settings == nil {
			g.settings = s
			g.mappings = obj(impl.Content["mappings"])
		}
	}
	pkg := text(g.settings["package"])
	if pkg == "" {
		pkg = "service"
	}
	g.db = text(g.settings["databaseNameId"])
	if g.db == "" {
		g.problem("error", "/", "the go-dxlib target's settings name no databaseNameId, the name dxlib knows the service's database by; add it")
		return g.response(nil)
	}
	g.entities = obj(g.spec["entities"])
	g.schemas = obj(g.spec["schemas"])
	g.values, g.columns, g.helpers = map[string]bool{}, map[string]bool{}, map[string]bool{}
	g.folds = map[string]bool{}
	g.collectLists()

	var body strings.Builder
	g.w = &body
	g.tables()
	g.handlers()
	g.seeds()
	g.tasks()
	g.valueTypes()
	if g.failed() {
		return g.response(nil)
	}
	var b strings.Builder
	info := obj(g.spec["info"])
	fmt.Fprintf(&b, "// Code generated by specarch-gen-go-dxlib from %s, version %s; meta-model %s. DO NOT EDIT.\n\n", relRoot(r.Root, r.Output), text(info["version"]), r.Specarch)
	fmt.Fprintf(&b, "// Package %s is %s on dxlib: its tables, the handler of each\n// operation, the privileges, roles and menu items as data, and its tasks.\n// Where a design gives no standard operation, a handler calls a body the\n// service writes beside this file.\npackage %s\n\n", pkg, text(info["title"]), pkg)
	b.WriteString("import (\n")
	var std, ext []string
	for i := range g.imports {
		if strings.Contains(strings.Split(i, "/")[0], ".") {
			ext = append(ext, i)
		} else {
			std = append(std, i)
		}
	}
	sort.Strings(std)
	sort.Strings(ext)
	for _, i := range std {
		fmt.Fprintf(&b, "\t%q\n", i)
	}
	if len(std) > 0 && len(ext) > 0 {
		b.WriteString("\n")
	}
	for _, i := range ext {
		fmt.Fprintf(&b, "\t%q\n", i)
	}
	b.WriteString(")\n\n")
	b.WriteString(body.String())
	if len(g.patterns) > 0 {
		b.WriteString("// The patterns the checks match against, compiled once.\nvar (\n")
		for _, p := range g.patterns {
			fmt.Fprintf(&b, "\t%s = regexp.MustCompile(%s)\n", p[0], strconv.Quote(p[1]))
		}
		b.WriteString(")\n")
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		g.problem("error", "/", "the generated Go does not parse (%v); this is a bug in specarch-gen-go-dxlib", err)
		return g.response(nil)
	}
	return g.response([]genopenapi.File{{Path: FileName, Content: string(src)}})
}

type gen struct {
	spec, settings, entities map[string]any
	mappings                 map[string]any
	owned                    ownership.Owned // operations and jobs another stakeholder owns get no code
	root, db                 string
	diags                    []genopenapi.Diagnostic
	imports                  map[string]bool
	w                        *strings.Builder
	search, sort, filter     map[string][]string // per entity, from the lists over it
	listView                 map[string]string   // per entity, the view its lists page through, "-" for none
	mixed                    map[string]bool     // entities listed in two ways, reported once
	patterns                 [][2]string         // the regexp variables the checks use: name, pattern
	schemas                  map[string]any
	values                   map[string]bool // the schemas a request carries, written as Go types
	columns                  map[string]bool // the schemas kept in columns, which write their parts into a row
	folds                    map[string]bool // the entities whose stored row is folded into the interface's shape
	helpers                  map[string]bool // the helper functions the file uses
}

func (g *gen) line(format string, args ...any) { fmt.Fprintf(g.w, format+"\n", args...) }

func (g *gen) problem(severity, path, format string, args ...any) {
	g.diags = append(g.diags, genopenapi.Diagnostic{File: g.root, Line: 1, Severity: severity, Path: path, Rule: "generator", Message: fmt.Sprintf(format, args...)})
}

func (g *gen) failed() bool {
	for _, d := range g.diags {
		if d.Severity == "error" {
			return true
		}
	}
	return false
}

func (g *gen) response(files []genopenapi.File) genopenapi.Response {
	if files == nil || g.failed() {
		files = []genopenapi.File{}
	}
	diags := g.diags
	if diags == nil {
		diags = []genopenapi.Diagnostic{}
	}
	return genopenapi.Response{Files: files, Diagnostics: diags}
}

// collectLists gathers, per entity, the fields its lists search, sort and
// filter by, as dxlib's table whitelists.
func (g *gen) collectLists() {
	g.search, g.sort, g.filter = map[string][]string{}, map[string][]string{}, map[string][]string{}
	g.listView, g.mixed = map[string]string{}, map[string]bool{}
	for _, o := range g.operations() {
		l := obj(o.node["listOf"])
		if l == nil {
			continue
		}
		e := g.listEntity(l)
		// A dxlib table pages through one list view, and reads by key and
		// counts through it too, so every list of an entity names the same
		// view, or none does.
		v := text(l["view"])
		if v == "" {
			v = "-" // listed directly
		}
		if prev, seen := g.listView[e]; seen && prev != v && !g.mixed[e] {
			g.mixed[e] = true
			g.problem("error", "/paths/"+strings.NewReplacer("~", "~0", "/", "~1").Replace(o.path)+"/"+o.method+"/listOf", "%s is listed through %s and through %s, and a dxlib table pages through one list view, which it also reads by key and counts through; list %s the same way everywhere", e, through(prev), through(v), e)
		}
		if _, seen := g.listView[e]; !seen {
			g.listView[e] = v
		}
		g.search[e] = union(g.search[e], wires(list(l["searchable"])))
		g.sort[e] = union(g.sort[e], wires(list(l["sortable"])))
		g.filter[e] = union(g.filter[e], wires(list(l["filterable"])))
	}
}

// keyed reports whether an entity has one primary key field of text, the
// uid dxlib reads a record by; its column name is answered.
func (g *gen) keyed(entity string) (string, bool) {
	e := obj(g.entities[entity])
	pk := list(e["primaryKey"])
	if len(pk) != 1 {
		return "", false
	}
	f := obj(obj(e["properties"])[text(pk[0])])
	t, _ := genopenapi.DXType(f)
	if t != "string" {
		return "", false
	}
	return genopenapi.Wire(text(pk[0])), true
}

// standard reports whether an entity's table is dxlib's DXTable, which
// keeps the audit fields and soft delete, rather than a DXRawTable.
func (g *gen) standard(entity string) bool {
	e := obj(g.entities[entity])
	return e["audited"] == true || text(e["deletion"]) == "soft"
}

// tables writes one dxlib table per entity.
func (g *gen) tables() {
	names := sortedKeys(g.entities)
	if len(names) == 0 {
		return
	}
	g.imports["github.com/donnyhardyanto/dxlib/tables"] = true
	g.line("// Tables holds the dxlib table of each entity. An audited or softly deleted")
	g.line("// entity is a DXTable, which keeps its audit fields and its deleted flag;")
	g.line("// any other is a DXRawTable.")
	g.line("var Tables = struct {")
	for _, n := range names {
		kind := "DXRawTable"
		if g.standard(n) {
			kind = "DXTable"
		}
		g.line("\t%s *tables.%s", n, kind)
	}
	g.line("}{")
	for _, n := range names {
		e := obj(g.entities[n])
		ctor := "NewDXRawTableSimple"
		if g.standard(n) {
			ctor = "NewDXTableSimple"
		}
		uid, _ := g.keyed(n)
		var uniques []string
		for _, c := range sortedKeys(obj(e["constraints"])) {
			con := obj(obj(e["constraints"])[c])
			if text(con["kind"]) == "unique" {
				uniques = append(uniques, "{"+quoteAll(wires(list(con["fields"])))+"}")
			}
		}
		if hasEncrypted(e) {
			g.problem("warning", "/entities/"+n, "%s has a field encrypted at rest; its encryption keys are the service's, so the table's EncryptionKeyDefs is left empty", n)
		}
		view := ""
		if v := g.listView[n]; v != "" && v != "-" {
			view = g.viewName(v)
		}
		g.line("\t%s: tables.%s(%q, %q, %q, %q, \"\", %q, \"\", \"\", nil, [][]string{%s}, []string{%s}, []string{%s}, []string{%s}),",
			n, ctor, g.db, g.tableName(n), snakeName(n), view, uid, strings.Join(uniques, ", "), quoteAll(g.search[n]), quoteAll(g.sort[n]), quoteAll(g.filter[n]))
	}
	g.line("}")
	g.line("")
}

// through names how a list reads its entity, for a diagnostic.
func through(view string) string {
	if view == "-" {
		return "itself"
	}
	return "the view " + view
}

// listEntity is the entity a list pages through, itself or the one its
// view reads from.
func (g *gen) listEntity(l map[string]any) string {
	if v := text(l["view"]); v != "" {
		return text(obj(obj(g.spec["views"])[v])["from"])
	}
	return text(l["entity"])
}

// viewName follows specarch-gen-sql's rule: the mapping's view, or the
// view's name in snake case.
func (g *gen) viewName(view string) string {
	target := text(obj(g.mappings["#/views/"+view])["target"])
	if rest, ok := strings.CutPrefix(target, "view "); ok {
		if i := strings.IndexAny(rest, " ,"); i >= 0 {
			rest = rest[:i]
		}
		if rest != "" {
			return rest
		}
	}
	return snakeName(view)
}

// tableName follows specarch-gen-sql's rule: the mapping's table, or the
// entity's name in snake case.
func (g *gen) tableName(entity string) string {
	target := text(obj(g.mappings["#/entities/"+entity])["target"])
	if rest, ok := strings.CutPrefix(target, "table "); ok {
		if i := strings.IndexAny(rest, " ,"); i >= 0 {
			rest = rest[:i]
		}
		if rest != "" {
			return rest
		}
	}
	return snakeName(entity)
}

func hasEncrypted(e map[string]any) bool {
	for _, f := range obj(e["properties"]) {
		if text(obj(f)["atRest"]) == "encrypted" {
			return true
		}
	}
	return false
}

// operation is one operation of the design.
type operation struct {
	id, path, method string
	node, item       map[string]any
}

// pointer is the operation's JSON pointer in the specification.
func (o operation) pointer() string {
	return "/paths/" + strings.NewReplacer("~", "~0", "/", "~1").Replace(o.path) + "/" + o.method
}

func (g *gen) operations() []operation {
	var out []operation
	paths := obj(g.spec["paths"])
	for _, p := range sortedKeys(paths) {
		item := obj(paths[p])
		for _, m := range []string{"get", "put", "post", "delete", "patch"} {
			if op := obj(item[m]); op != nil && !g.owned.Covers(ownership.Operation(p, m)) {
				out = append(out, operation{id: text(op["operationId"]), path: p, method: m, node: op, item: item})
			}
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].id < out[j].id })
	return out
}

// param is one parameter of an operation as dxlib reads it.
type param struct {
	name        string // the design's name
	wire, field string // the name on the wire, and the accessor's field
	schema      map[string]any
	required    bool
}

// params lists an operation's parameters: path, query and body, as the
// dxlib dialect puts them in one body.
func (g *gen) params(o operation) []param {
	seen := map[string]bool{}
	var out []param
	addp := func(name string, s map[string]any, req bool) {
		w := genopenapi.Wire(name)
		if seen[w] {
			return
		}
		seen[w] = true
		out = append(out, param{name: name, wire: w, field: pascal(name), schema: s, required: req})
	}
	for _, p := range append(list(o.item["parameters"]), list(o.node["parameters"])...) {
		pm := obj(p)
		if text(pm["in"]) != "header" {
			addp(text(pm["name"]), obj(pm["schema"]), pm["required"] == true)
		}
	}
	for _, c := range obj(obj(o.node["requestBody"])["content"]) {
		s := obj(obj(c)["schema"])
		required := map[string]bool{}
		props := obj(s["properties"])
		if r := text(s["$ref"]); strings.HasPrefix(r, "#/entities/") || strings.HasPrefix(r, "#/schemas/") {
			e := obj(g.entities[strings.TrimPrefix(r, "#/entities/")])
			if name, ok := strings.CutPrefix(r, "#/schemas/"); ok {
				e = obj(obj(g.spec["schemas"])[name])
			}
			props = map[string]any{}
			for k, v := range obj(e["properties"]) {
				if obj(v)["readOnly"] != true {
					props[k] = v
				}
			}
			s = e
		}
		for _, r := range list(s["required"]) {
			required[text(r)] = true
		}
		for _, k := range sortedKeys(props) {
			addp(k, obj(props[k]), required[k])
		}
		break
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].wire < out[j].wire })
	return out
}

// goType is the Go type of a parameter and the dxlib getter that reads it.
func (g *gen) goType(s map[string]any) (typ, getter string) {
	if name, many := valueObjectOf(s); name != "" && g.schemas[name] != nil {
		g.useValue(name)
		if many {
			return "[]" + pascal(name), readValue
		}
		return "*" + pascal(name), readValue
	}
	t, _ := genopenapi.DXType(s)
	// A nullable type reads as its base: dxlib's getter answers a null and a
	// left-out parameter alike, with Has false.
	t = strings.TrimPrefix(t, "nullable-")
	switch {
	case strings.HasPrefix(t, "int32"):
		return "int32", "GetParameterValueAsInt32"
	case strings.HasPrefix(t, "int64"):
		return "int64", "GetParameterValueAsInt64"
	case strings.HasPrefix(t, "float64"):
		return "float64", "GetParameterValueAsFloat64"
	case t == "money":
		g.imports["github.com/shopspring/decimal"] = true
		return "decimal.Decimal", "GetParameterValueAsDecimal"
	case t == "bool":
		return "bool", "GetParameterValueAsBool"
	case t == "iso8601":
		g.imports["time"] = true
		return "time.Time", "GetParameterValueAsTime"
	case t == "json" || t == "json-passthrough":
		g.imports["github.com/donnyhardyanto/dxlib/utils"] = true
		return "utils.JSON", "GetParameterValueAsJSON"
	case t == "array-string":
		return "[]string", "GetParameterValueAsStrings"
	case t == "array-int64":
		return "[]int64", "GetParameterValueAsInt64s"
	case strings.HasPrefix(t, "array"):
		return "[]any", "GetParameterValueAsArrayOfAny"
	}
	return "string", "GetParameterValueAsString"
}

// defaultValue is the Go literal of a field's design default, which a
// handler takes when the value is not given: left out, or sent as null,
// which dxlib reads alike. A default with no Go literal here is reported.
func (g *gen) defaultValue(at, wire string, s map[string]any) (string, bool) {
	v, ok := s["default"]
	if !ok || v == nil {
		return "", false
	}
	typ, _ := g.goType(s)
	switch typ {
	case "string":
		return fmt.Sprintf("%q", text(v)), true
	case "int32", "int64", "float64", "bool":
		return fmt.Sprintf("%v", v), true
	case "decimal.Decimal":
		return fmt.Sprintf("decimal.RequireFromString(%q)", text(v)), true
	}
	g.problem("warning", at, "the default of %s has no Go literal for a %s; apply it in the service", wire, typ)
	return "", false
}

// handlers writes the registration, and per operation its accessor, its
// checks and its handler.
func (g *gen) handlers() {
	ops := g.operations()
	if len(ops) == 0 {
		return
	}
	g.imports["github.com/donnyhardyanto/dxlib/api"] = true
	g.line("// Register binds each operation's handler to its operationId, as the")
	g.line("// document of the dxlib dialect names it.")
	g.line("func Register(a *api.DXAPI) {")
	for _, o := range ops {
		g.line("\ta.RegisterHandler(%q, %s)", o.id, pascal(o.id))
	}
	g.line("}")
	g.line("")
	for _, o := range ops {
		g.operation(o)
	}
}

func (g *gen) operation(o operation) {
	name := pascal(o.id)
	params := g.params(o)
	req := name + "Request"
	g.line("// %s holds the parameters of %s; Has says whether one was given.", req, o.id)
	g.line("type %s struct {", req)
	for _, p := range params {
		typ, _ := g.goType(p.schema)
		g.line("\t%s %s", p.field, typ)
		g.line("\tHas%s bool", p.field)
	}
	g.line("}")
	g.line("")
	g.line("func read%s(aepr *api.DXAPIEndPointRequest) (r %s, err error) {", req, req)
	for _, p := range params {
		typ, getter := g.goType(p.schema)
		if getter == readValue {
			g.helper("readValue")
			g.line("\tif r.Has%s, r.%s, err = readValue[%s](aepr, %q); err != nil {", p.field, p.field, typ, p.wire)
		} else {
			g.line("\tif r.Has%s, r.%s, err = aepr.%s(%q); err != nil {", p.field, p.field, getter, p.wire)
		}
		g.line("\t\treturn r, err")
		g.line("\t}")
		if v, ok := g.defaultValue(o.pointer(), p.wire, p.schema); ok {
			g.line("\tif !r.Has%s {", p.field)
			g.line("\t\tr.%s = %s", p.field, v)
			g.line("\t}")
		}
	}
	g.line("\treturn r, nil")
	g.line("}")
	g.line("")
	g.checks(o, name, req, params)

	g.line("// %s handles %s.", name, o.id)
	g.line("func %s(aepr *api.DXAPIEndPointRequest) error {", name)
	g.line("\tr, err := read%s(aepr)", req)
	g.line("\tif err != nil {")
	g.line("\t\treturn err")
	g.line("\t}")
	g.line("\tif err := check%s(aepr, r); err != nil {", name)
	g.line("\t\treturn err")
	g.line("\t}")
	switch kind, entity := g.kind(o); kind {
	case "list":
		g.listBody(o, entity)
	case "create":
		g.createBody(entity, params)
	case "read":
		g.readBody(entity, params)
	default:
		g.line("\treturn body%s(aepr, r)", name)
	}
	g.line("}")
	g.line("")
}

// kind is the standard operation an operation is, with its entity: a list,
// a create, a read by key, or "" for one whose body the service writes.
func (g *gen) kind(o operation) (string, string) {
	if l := obj(o.node["listOf"]); l != nil {
		return "list", g.listEntity(l)
	}
	entity := responseEntity(o.node)
	if entity == "" {
		return "", ""
	}
	if _, ok := g.keyed(entity); !ok {
		return "", ""
	}
	body := text(obj(obj(obj(obj(o.node["requestBody"])["content"])["application/json"])["schema"])["$ref"])
	if o.method == "post" && body == "#/entities/"+entity && obj(o.node["responses"])["201"] != nil {
		return "create", entity
	}
	var pathParams int
	for _, p := range append(list(o.item["parameters"]), list(o.node["parameters"])...) {
		if text(obj(p)["in"]) == "path" {
			pathParams++
		}
	}
	if o.method == "get" && pathParams == 1 && obj(o.node["requestBody"]) == nil {
		return "read", entity
	}
	return "", ""
}

func responseEntity(op map[string]any) string {
	for code, r := range obj(op["responses"]) {
		if !strings.HasPrefix(code, "2") {
			continue
		}
		s := obj(obj(obj(obj(r)["content"])["application/json"])["schema"])
		if ref := text(s["$ref"]); strings.HasPrefix(ref, "#/entities/") {
			return strings.TrimPrefix(ref, "#/entities/")
		}
	}
	return ""
}

func (g *gen) listBody(o operation, entity string) {
	if max := text(obj(obj(o.node["listOf"])["pageSize"])["maximum"]); max != "" {
		g.imports["net/http"] = true
		g.line("\tif _, size, err := aepr.GetParameterValueAsInt64(%q); err != nil {", "row_per_page")
		g.line("\t\treturn err")
		g.line("\t} else if size > %s {", max)
		g.line("\t\treturn aepr.WriteResponseAndNewErrorf(http.StatusUnprocessableEntity, \"\", \"%%s\", \"INVALID_PARAMETER:row_per_page:maximum: %s\")", max)
		g.line("\t}")
	}
	if g.holdsValues(entity) {
		g.problem("warning", o.pointer(), "%s lists %s through dxlib's paging list, which answers each row as it is stored: a value kept in columns as the columns of its parts, and one kept as JSON as its text; give the rows the interface's shape in the service", o.id, entity)
	}
	g.line("\treturn Tables.%s.RequestSearchPagingList(aepr)", entity)
}

func (g *gen) createBody(entity string, params []param) {
	g.imports["net/http"] = true
	g.imports["github.com/donnyhardyanto/dxlib/utils"] = true
	uid, _ := g.keyed(entity)
	g.line("\tdata := utils.JSON{}")
	for _, p := range params {
		if g.storeValue(entity, p) {
			continue
		}
		if _, ok := p.schema["default"]; ok && p.schema["default"] != nil {
			g.line("\tdata[%q] = r.%s", p.wire, p.field)
			continue
		}
		g.line("\tif r.Has%s {", p.field)
		g.line("\t\tdata[%q] = r.%s", p.wire, p.field)
		g.line("\t}")
	}
	key := obj(obj(obj(g.entities[entity])["properties"])[text(list(obj(g.entities[entity])["primaryKey"])[0])])
	if text(key["format"]) == "uuid" && key["readOnly"] == true {
		g.imports["github.com/google/uuid"] = true
		g.line("\tdata[%q] = uuid.NewString()", uid)
	}
	if g.standard(entity) {
		g.line("\tTables.%s.SetInsertAuditFields(aepr, data)", entity)
	}
	g.line("\tif _, _, err := Tables.%s.Insert(aepr.Context, &aepr.Log, data, nil); err != nil {", entity)
	g.line("\t\treturn err")
	g.line("\t}")
	g.line("\tuid, _ := data[%q].(string)", uid)
	g.line("\t_, row, err := Tables.%s.GetByUidAuto(aepr.Context, &aepr.Log, uid)", entity)
	g.line("\tif err != nil {")
	g.line("\t\treturn err")
	g.line("\t}")
	g.foldRow(entity)
	g.line("\taepr.WriteResponseAsJSON(http.StatusCreated, nil, row)")
	g.line("\treturn nil")
}

func (g *gen) readBody(entity string, params []param) {
	g.imports["net/http"] = true
	var key param
	for _, p := range params {
		if p.required {
			key = p
			break
		}
	}
	get := "GetByUidAuto"
	if g.standard(entity) {
		get = "GetByUidNotDeletedAuto"
	}
	g.line("\t_, row, err := Tables.%s.%s(aepr.Context, &aepr.Log, r.%s)", entity, get, key.field)
	g.line("\tif err != nil {")
	g.line("\t\treturn err")
	g.line("\t}")
	g.line("\tif row == nil {")
	g.line("\t\treturn aepr.WriteResponseAndNewErrorf(http.StatusNotFound, \"\", \"%s_NOT_FOUND:%%s\", r.%s)", strings.ToUpper(snakeName(entity)), key.field)
	g.line("\t}")
	g.foldRow(entity)
	g.line("\taepr.WriteResponseAsJSON(http.StatusOK, nil, row)")
	g.line("\treturn nil")
}

// checks writes the checks of the constraints dxlib's validator does not
// apply, which the document lists as unenforced.
func (g *gen) checks(o operation, name, req string, params []param) {
	g.line("// check%s checks what dxlib's validator does not: the constraints the", name)
	g.line("// document lists under x-specarch-unenforced.")
	g.line("func check%s(aepr *api.DXAPIEndPointRequest, r %s) error {", name, req)
	for _, p := range params {
		g.missingCheck(p)
	}
	for _, p := range params {
		typ, _ := g.goType(p.schema)
		for _, u := range genopenapi.Unenforced(p.schema) {
			k, v, _ := strings.Cut(u, ": ")
			cond := g.condition(k, v, typ, "r."+p.field)
			if cond == "" {
				g.problem("warning", o.pointer(), "%s's %s of %s is not checked by dxlib, and go-dxlib has no check for it; check it in the service", o.id, u, p.wire)
				continue
			}
			g.imports["net/http"] = true
			g.line("\tif r.Has%s && %s {", p.field, cond)
			g.line("\t\treturn aepr.WriteResponseAndNewErrorf(http.StatusUnprocessableEntity, \"\", \"%%s\", %q)", "INVALID_PARAMETER:"+p.wire+":"+u)
			g.line("\t}")
		}
	}
	g.line("\treturn nil")
	g.line("}")
	g.line("")
}

// uuidPattern is the text form of a UUID.
const uuidPattern = `^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`

// condition is the Go that is true when a value breaks a constraint, or ""
// when go-dxlib has no check for it.
func (g *gen) condition(key, value, typ, v string) string {
	numeric := strings.HasPrefix(typ, "int") || typ == "float64"
	switch {
	case key == "maxLength" && typ == "string":
		g.imports["unicode/utf8"] = true
		return fmt.Sprintf("utf8.RuneCountInString(%s) > %s", v, value)
	case key == "minLength" && typ == "string":
		g.imports["unicode/utf8"] = true
		return fmt.Sprintf("utf8.RuneCountInString(%s) < %s", v, value)
	case key == "pattern" && typ == "string":
		return fmt.Sprintf("!%s.MatchString(%s)", g.pattern(value), v)
	case key == "format" && value == "uuid" && typ == "string":
		return fmt.Sprintf("!%s.MatchString(%s)", g.pattern(uuidPattern), v)
	case key == "maximum" && numeric:
		return fmt.Sprintf("%s > %s", v, value)
	case key == "minimum" && numeric:
		return fmt.Sprintf("%s < %s", v, value)
	case key == "exclusiveMaximum" && numeric:
		return fmt.Sprintf("%s >= %s", v, value)
	case (key == "maxItems") && strings.HasPrefix(typ, "[]"):
		return fmt.Sprintf("len(%s) > %s", v, value)
	case (key == "minItems") && strings.HasPrefix(typ, "[]"):
		return fmt.Sprintf("len(%s) < %s", v, value)
	}
	return ""
}

// pattern is the variable holding a compiled pattern, declared once.
func (g *gen) pattern(p string) string {
	g.imports["regexp"] = true
	for _, have := range g.patterns {
		if have[1] == p {
			return have[0]
		}
	}
	name := fmt.Sprintf("pattern%d", len(g.patterns)+1)
	g.patterns = append(g.patterns, [2]string{name, p})
	return name
}

// seeds writes the permissions, roles and menu items as data.
func (g *gen) seeds() {
	perms, roles, menus := obj(g.spec["permissions"]), obj(g.spec["roles"]), obj(g.spec["menus"])
	if len(perms)+len(roles)+len(menus) == 0 {
		return
	}
	g.line("// Privilege is a permission of the specification, as a privilege row of")
	g.line("// dxlib_module's user management. Seeding them is the service's.")
	g.line("type Privilege struct{ NameId, Description string }")
	g.line("")
	g.line("// Role is a role of the specification with the privileges it grants.")
	g.line("type Role struct {")
	g.line("\tNameId, Description string")
	g.line("\tPrivilegeNameIds    []string")
	g.line("}")
	g.line("")
	g.line("// MenuItem is an entry of the menu: a page, shown to who has its")
	g.line("// privilege, or a group of entries.")
	g.line("type MenuItem struct {")
	g.line("\tNameId, Title, Page, PrivilegeNameId string")
	g.line("\tChildren                            []MenuItem")
	g.line("}")
	g.line("")
	g.line("// Privileges are the specification's permissions.")
	g.line("var Privileges = []Privilege{")
	for _, p := range sortedKeys(perms) {
		if p == "public" {
			continue // open to everyone, so no privilege grants it
		}
		g.line("\t{%q, %q},", p, oneLine(text(obj(perms[p])["description"])))
	}
	g.line("}")
	g.line("")
	g.line("// Roles are the specification's roles.")
	g.line("var Roles = []Role{")
	for _, r := range sortedKeys(roles) {
		role := obj(roles[r])
		g.line("\t{%q, %q, []string{%s}},", r, oneLine(text(role["description"])), quoteAll(texts(list(role["permissions"]))))
	}
	g.line("}")
	g.line("")
	g.line("// MenuItems is the specification's menu.")
	g.line("var MenuItems = []MenuItem{")
	g.menu(menus, "\t")
	g.line("}")
	g.line("")
}

func (g *gen) menu(items map[string]any, indent string) {
	pages := obj(g.spec["pages"])
	for _, k := range sortedKeys(items) {
		m := obj(items[k])
		page := text(m["page"])
		perm := text(obj(pages[page])["permission"])
		if perm == "public" {
			perm = ""
		}
		if children := obj(m["items"]); children != nil {
			g.line("%s{NameId: %q, Title: %q, Children: []MenuItem{", indent, k, text(m["title"]))
			g.menu(children, indent+"\t")
			g.line("%s}},", indent)
			continue
		}
		g.line("%s{NameId: %q, Title: %q, Page: %q, PrivilegeNameId: %q},", indent, k, text(m["title"]), page, perm)
	}
}

// tasks writes a dxlib task per job that repeats at an interval.
func (g *gen) tasks() {
	jobs := obj(g.spec["jobs"])
	var repeating []string
	for _, name := range sortedKeys(jobs) {
		if g.owned.Covers(ownership.Entity("jobs", name)) {
			continue
		}
		trigger := obj(obj(jobs[name])["trigger"])
		if text(trigger["every"]) == "" {
			g.problem("warning", "/jobs/"+name, "dxlib's tasks run once or repeat after a delay, so job %s, started by a schedule or a message, is the service's to start", name)
			continue
		}
		repeating = append(repeating, name)
	}
	if len(repeating) == 0 {
		return
	}
	g.imports["github.com/donnyhardyanto/dxlib/task"] = true
	g.line("// RegisterTasks adds a dxlib task per job that repeats at an interval. Each")
	g.line("// calls a job function the service writes.")
	g.line("func RegisterTasks() error {")
	for _, name := range repeating {
		secs, ok := seconds(text(obj(obj(jobs[name])["trigger"])["every"]))
		if !ok {
			g.problem("error", "/jobs/"+name+"/trigger/every", "the interval of job %s is not one this version can read", name)
			continue
		}
		g.line("\tif _, err := task.Manager.NewTask(%q, \"always\", %d, job%s); err != nil {", name, secs, pascal(name))
		g.line("\t\treturn err")
		g.line("\t}")
	}
	g.line("\treturn nil")
	g.line("}")
	g.line("")
}

// seconds reads an ISO 8601 duration of days, hours, minutes and seconds.
func seconds(d string) (int64, bool) {
	rest, ok := strings.CutPrefix(d, "P")
	if !ok {
		return 0, false
	}
	var total int64
	inTime := false
	num := ""
	for _, r := range rest {
		switch {
		case r == 'T':
			inTime = true
		case unicode.IsDigit(r):
			num += string(r)
		default:
			n, err := strconv.ParseInt(num, 10, 64)
			if err != nil {
				return 0, false
			}
			num = ""
			switch {
			case r == 'D' && !inTime:
				total += n * 86400
			case r == 'H' && inTime:
				total += n * 3600
			case r == 'M' && inTime:
				total += n * 60
			case r == 'S' && inTime:
				total += n
			default:
				return 0, false
			}
		}
	}
	return total, num == ""
}

// Small helpers.

func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

func snakeName(s string) string { return genopenapi.Wire(s) }

func wires(l []any) []string {
	var out []string
	for _, v := range l {
		out = append(out, genopenapi.Wire(text(v)))
	}
	return out
}

func union(a, b []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range append(a, b...) {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

func quoteAll(items []string) string {
	var q []string
	for _, s := range items {
		q = append(q, strconv.Quote(s))
	}
	return strings.Join(q, ", ")
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func relRoot(root, output string) string {
	absRoot, err1 := filepath.Abs(filepath.FromSlash(root))
	absOut, err2 := filepath.Abs(filepath.FromSlash(output))
	if err1 != nil || err2 != nil {
		return root
	}
	rel, err := filepath.Rel(absOut, absRoot)
	if err != nil {
		return root
	}
	return filepath.ToSlash(rel)
}

func obj(v any) map[string]any {
	m, _ := v.(map[string]any)
	return m
}

func list(v any) []any {
	l, _ := v.([]any)
	return l
}

func texts(l []any) []string {
	var out []string
	for _, v := range l {
		out = append(out, text(v))
	}
	return out
}

func text(v any) string {
	switch x := v.(type) {
	case nil:
		return ""
	case string:
		return x
	}
	return fmt.Sprint(v)
}

func sortedKeys(m map[string]any) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
