func write(t *testing.T, opt Options) []byte {
	t.Helper()
	data, err := Write(opt)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

// TestSameBytes requires two runs to write the same bytes: nothing comes
// from the clock or from a map's order.
func TestSameBytes(t *testing.T) {
	a, b := write(t, testOptions()), write(t, testOptions())
	if !bytes.Equal(a, b) {
		t.Fatal("two runs wrote different bytes")
	}
}

// TestStructure checks the package against the rules of ISO/IEC 29500 a
// reader enforces when it opens a file: every part typed and reachable,
// every relationship's target there, every element's children in the
// schema's order, every table cell holding a paragraph and the grid
// matching the rows, the section properties last in the body, every
// style, numbering, bookmark and link resolved.
func TestStructure(t *testing.T) {
	checkPackage(t, write(t, testOptions()))
}

// TestEmptyBook checks a book with no parts and no marks.
func TestEmptyBook(t *testing.T) {
	opt := testOptions()
	opt.Parts = nil
	opt.IsMark = nil
	data := write(t, opt)
	checkPackage(t, data)
	if text := documentText(t, data); !strings.Contains(text, "No problem or gap is marked.") {
		t.Errorf("the book does not say nothing is marked:\n%s", text)
	}
}

// TestContent checks what the book says: the headings in Word's heading
// styles, the marks shaded and listed, the links resolved, a link that
// leads nowhere written with its target, ids linked to what describes
// them, the header and footer, A4 pages.
func TestContent(t *testing.T) {
	data := write(t, testOptions())
	parts := readParts(t, data)
	doc := parts["word/document.xml"]
	for _, want := range []string{
		`<w:pStyle w:val="Title"/>`,
		`<w:pStyle w:val="Heading1"/>`,
		`<w:pStyle w:val="Heading2"/>`,
		`<w:pStyle w:val="TOCHeading"/>`,
		`<w:pStyle w:val="TOC1"/>`,
		`<w:pStyle w:val="Mark"/>`,
		`<w:pStyle w:val="CodeBlock"/>`,
		`<w:pStyle w:val="Caption"/>`,
		`<w:tblHeader/>`,
		`<w:pgSz w:w="11906" w:h="16838"/>`,
		`w:anchor="id_REQ_1"`,
		`w:anchor="traceability_matrix"`,
		`<w:t xml:space="preserve"> (../spec/specarch.yaml)</w:t>`,
		`refines </w:t>`,
		` &amp; keeps &lt;tags&gt; safe.`,
		`TOC \o &#34;1-3&#34;`,
	} {
		if !strings.Contains(doc, want) && !strings.Contains(doc, strings.ReplaceAll(want, "&#34;", `"`)) {
			t.Errorf("document.xml has no %s", want)
		}
	}
	if !strings.Contains(parts["word/_rels/document.xml.rels"], `Target="https://example.org/a?b=1&amp;c=2" TargetMode="External"`) {
		t.Errorf("the external link is not a relationship with its target:\n%s", parts["word/_rels/document.xml.rels"])
	}
	if !strings.Contains(parts["word/header1.xml"], "Lending: test book, version 1.0.0") {
		t.Error("the header does not name the book and its version")
	}
	if !strings.Contains(parts["word/footer1.xml"], `w:instr=" PAGE "`) || !strings.Contains(parts["word/footer1.xml"], `w:instr=" NUMPAGES "`) {
		t.Error("the footer has no page number and page count fields")
	}
	if strings.Count(doc, `<w:pStyle w:val="Mark"/>`) != 3 || strings.Count(doc, `<w:pStyle w:val="ProblemEntry"/>`) != 3 {
		t.Errorf("want 3 marks and 3 entries in the list, got %d and %d", strings.Count(doc, `<w:pStyle w:val="Mark"/>`), strings.Count(doc, `<w:pStyle w:val="ProblemEntry"/>`))
	}
	if !strings.Contains(doc, `<w:t xml:space="preserve">    indented line</w:t>`) {
		t.Error("a tab in a fenced block is not four spaces kept")
	}
	if !strings.Contains(parts["word/numbering.xml"], `<w:num w:numId="2"><w:abstractNumId w:val="1"/><w:lvlOverride w:ilvl="0"><w:startOverride w:val="3"/>`) {
		t.Error("the numbered list does not start at its first number, 3")
	}
	if strings.Contains(parts["docProps/core.xml"], "dcterms:created") || strings.Contains(parts["docProps/core.xml"], "dcterms:modified") {
		t.Error("core.xml holds a date")
	}
}

