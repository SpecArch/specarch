func testOptions() Options {
	return Options{
		Title:       "Lending: test book",
		Lang:        "en",
		FrontMatter: testFront,
		Parts:       []Part{{Name: "requirements", Markdown: testRequirements}, {Name: "traceability", Markdown: testTraceability}},
		IDs:         map[string]bool{"LEND-1": true, "LEND-2": true, "NEED-1": true},
		Slug: func(s string) string {
			return strings.ToLower(strings.ReplaceAll(s, " ", "-"))
		},
		IsMark: func(lead, text string) bool {
			return strings.HasPrefix(lead, "Gap") || strings.HasPrefix(lead, "Problem") && strings.HasSuffix(text, "]")
		},
		Texts: testTexts,
	}
}

func write(t *testing.T, opt Options) []byte {
	t.Helper()
	out, err := Write(opt)
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func open(t *testing.T, data []byte) *reader.Reader {
	t.Helper()
	r, err := reader.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		t.Fatalf("the book does not read as a PDF: %v", err)
	}
	return r
}

// TestBookSameBytes requires the same input to give the same bytes, so
// --check and approve can compare a book.
func TestBookSameBytes(t *testing.T) {
	a, b := write(t, testOptions()), write(t, testOptions())
	if !bytes.Equal(a, b) {
		t.Fatal("two books made from the same input differ")
	}
	if !bytes.HasPrefix(a, []byte("%PDF-1.7\n")) || !bytes.HasSuffix(a, []byte("%%EOF\n")) {
		t.Fatalf("the book does not start with the PDF 1.7 header or end with %%%%EOF")
	}
	for _, clock := range []string{"/CreationDate", "/ModDate"} {
		if bytes.Contains(a, []byte(clock)) {
			t.Errorf("the book holds %s, a date from the clock", clock)
		}
	}
}

// TestBookStructure requires A4 pages, the tagged catalogue with its
// language, the structure tree, the outline, the destinations of the
// headings, the mark and its list entry, and the links between them.
func TestBookStructure(t *testing.T) {
	r := open(t, write(t, testOptions()))
	root := r.Trailer().Key("Root")
	if !root.Key("MarkInfo").Key("Marked").Bool() {
		t.Error("the catalogue does not say the file is tagged (MarkInfo Marked true)")
	}
	if lang := root.Key("Lang").RawString(); lang != "en" {
		t.Errorf("the catalogue's language is %q, want en", lang)
	}
	st := root.Key("StructTreeRoot")
	if st.Key("Type").Name() != "StructTreeRoot" {
		t.Fatal("the catalogue has no structure tree")
	}
	types := map[string]int{}
	var walk func(v reader.Value)
	walk = func(v reader.Value) {
		if v.Kind() == reader.Dict && v.Key("Type").Name() == "StructElem" {
			types[v.Key("S").Name()]++
		}
		k := v.Key("K")
		for i := 0; i < k.Len(); i++ {
			walk(k.Index(i))
		}
	}
	walk(st)
	for _, typ := range []string{"Document", "H1", "H2", "P", "L", "LI", "Lbl", "LBody", "Table", "TR", "TH", "TD", "Link", "TOC", "TOCI", "Code", "BlockQuote"} {
		if types[typ] == 0 {
			t.Errorf("the structure tree has no %s element; it has %v", typ, types)
		}
	}
	if r.NumPage() < 4 {
		t.Fatalf("the book has %d pages; the front matter, the contents, each document and the list each start one", r.NumPage())
	}
	for i := 1; i <= r.NumPage(); i++ {
		mb := r.Page(i).V.Key("MediaBox")
		if mb.Len() != 4 || mb.Index(2).Float64() != 595.28 || mb.Index(3).Float64() != 841.89 {
			t.Errorf("page %d is %v, not A4", i, mb)
		}
		if r.Page(i).V.Key("StructParents").Kind() != reader.Integer {
			t.Errorf("page %d has no StructParents", i)
		}
	}
	outline := root.Key("Outlines")
	var titles []string
	for o := outline.Key("First"); o.Kind() == reader.Dict; o = o.Key("Next") {
		titles = append(titles, o.Key("Title").Text())
	}
	want := []string{"Lending: test book", "Contents", "Lending: requirements", "Lending: traceability", "Problems and gaps"}
	if strings.Join(titles, "|") != strings.Join(want, "|") {
		t.Errorf("the outline's first level is %q, want %q", titles, want)
	}
	dests := root.Key("Dests")
	if n := len(dests.Keys()); n < 8 {
		t.Errorf("the book has %d named destinations; every heading, the mark, its entry and the id rows need one", n)
	}
	for _, k := range dests.Keys() {
		if len(k) > 127 {
			t.Errorf("destination name %q is longer than the 127 bytes a PDF name may be", k)
		}
	}
}

// TestBookText requires the text to be real text, the marks and the ids
// linked, a link outside the book printed with its target, a character
// no font has written as its code point, and the list to hold both marks.
func TestBookText(t *testing.T) {
	data := write(t, testOptions())
	r := open(t, data)
	var all strings.Builder
	links := 0
	for i := 1; i <= r.NumPage(); i++ {
		p := r.Page(i)
		text, err := p.GetPlainText(nil)
		if err != nil {
			t.Fatalf("page %d: %v", i, err)
		}
		all.WriteString(text)
		annots := p.V.Key("Annots")
		for j := 0; j < annots.Len(); j++ {
			a := annots.Index(j)
			if a.Key("Subtype").Name() == "Link" && (a.Key("Dest").Kind() == reader.Name || a.Key("A").Kind() == reader.Dict) {
				links++
			}
		}
	}
	text := strings.Join(strings.Fields(all.String()), " ")
	for _, want := range []string{
		"Lending: test book", "Contents", "A member borrows a copy", "(../spec/specarch.yaml)", "[U+2318] marks a character",
		"Mermaid diagram, printed as its source.", "flowchart LR", "a | b", "Problems and gaps", "2 problems and gaps are marked.",
		"Gap: version 1.0.0 is not dated.", "Problem: warning: unverified", "Page 1 of",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("the book's text does not hold %q:\n%s", want, text)
		}
	}
	// The contents (one per heading), the matrix link, the ids, the two
	// marks and their two list entries at least.
	if links < 15 {
		t.Errorf("the book has %d links; want the contents, the ids, the marks and the list entries linked", links)
	}
}

// TestBookNoMarks writes the list's sentence for a book with nothing
