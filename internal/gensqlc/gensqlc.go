// Package gensqlc writes the sqlc queries a specification derives: one per
// operation that writes an entity's record or reads one by its key, and
// one per list with its filters, search, sorts and page, with a second
// query for the list's total. Every other query is written by hand beside
// them, which is sqlc's own rule: the query is the reviewed input. The
// tables and columns are the ones specarch-gen-sql writes, read through
// gensql.Schema, so a query never names a column the migrations do not
// create.
package gensqlc

import (
	"bytes"
	"encoding/json"
	"fmt"
	"slices"
	"sort"
	"strings"

	"github.com/SpecArch/specarch/internal/gensql"
	"github.com/SpecArch/specarch/internal/mark"
	"github.com/SpecArch/specarch/internal/ownership"
	"github.com/SpecArch/specarch/internal/wirename"
)

// Request is what specarch writes on a plug-in's standard input.
type Request struct {
	gensql.Request
	// Check is true when specarch only compares the output with the disk,
	// so a file built by hand is compared rather than refused.
	Check bool `json:"check"`
}

// Decode reads a request, keeping numbers as their text.
func Decode(data []byte) (*Request, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	var r Request
	if err := dec.Decode(&r); err != nil {
		return nil, err
	}
	return &r, nil
}

// The plug-in's name, as its header and its messages give it.
const name = "specarch-gen-sqlc"

// engines are the dialects sqlc has an engine for, and the one this
// plug-in writes.
var engines = map[string]string{"postgresql": "postgresql", "mariadb": "mysql"}

type gen struct {
	spec   map[string]any
	root   string
	wire   string // the specification's wireNames rule
	owned  ownership.Owned
	tables map[string]gensql.Table // by entity
	diags  []gensql.Diagnostic
	placed map[string][]mark.Problem
	files  map[string]*file // by table
}

// file is one table's queries.
type file struct {
	entity  string
	queries []string
}

// Generate writes the queries of a request.
func Generate(r *Request) gensql.Response {
	g := &gen{spec: r.Specification, root: r.Root, files: map[string]*file{}, tables: map[string]gensql.Table{}}
	g.wire = text(obj0(g.spec["info"])["wireNames"])
	dialect := "postgresql"
	var impl gensql.Implementation
	for _, i := range r.Implementations {
		if t, ok := obj(obj0(i.Content["targets"])[r.Target]); ok || len(r.Implementations) == 1 {
			impl = i
			if d := text(t["dialect"]); d != "" {
				dialect = d
			}
			break
		}
	}
	g.owned = ownership.Of(impl.Content)
	if dialect != "postgresql" {
		why := "sqlc has no engine for it"
		if engines[dialect] != "" {
			why = "sqlc reads it as " + engines[dialect] + ", whose queries this version does not write yet"
		}
		g.problem("error", "/", "%s writes PostgreSQL queries only, and the sqlc target names %s: %s; write those queries by hand, or generate them for postgresql", name, dialect, why)
		return g.response(nil)
	}
	tables, version, diags := gensql.Schema(&r.Request)
	if len(diags) > 0 {
		for _, d := range diags {
			d.Message = strings.Replace(d.Message, "specarch-gen-sql", name, 1)
			g.diags = append(g.diags, d)
		}
		return g.response(nil)
	}
	for _, t := range tables {
		g.tables[t.Entity] = t
	}
	g.place(r)

	paths := obj0(g.spec["paths"])
	for _, p := range sortedKeys(paths) {
		item := obj0(paths[p])
		for _, method := range []string{"get", "put", "patch", "post"} {
			if op := obj0(item[method]); op != nil {
				g.operation(p, method, op, item)
			}
		}
	}

	header := fmt.Sprintf("-- Generated by %s from %s, version %s; meta-model %s; postgresql through type-rendering %s. Do not edit this file: a change goes into the specification, and a query it does not derive goes into a file of your own.\n",
		name, relRoot(r.Root, r.Output), text(obj0(g.spec["info"])["version"]), r.Specarch, version)
	if r.Draft != "" {
		header += "-- " + r.Draft + "\n"
	}
	header += g.marks(mark.File)
	var files []gensql.File
	for _, t := range sortedKeys(g.files) {
		f := g.files[t]
		files = append(files, gensql.File{Path: t + ".sql", Content: header + g.marks("/entities/"+mark.Escape(f.entity)) + strings.Join(f.queries, "\n")})
	}
	if !r.Check && g.handWritten(files, r.Existing) {
		return g.response(nil)
	}
	return g.response(files)
}

// operation writes the query an operation derives, when it derives one.
func (g *gen) operation(path, method string, op, item map[string]any) {
	at := "/paths/" + mark.Escape(path) + "/" + method
	id := text(op["operationId"])
	if id == "" {
		return
	}
	params := parameters(item, op)
	if lo := obj0(op["listOf"]); lo != nil {
		g.list(at, path, id, lo, params)
		return
	}
	var keyed []map[string]any
	for _, p := range params {
		if text(p["in"]) == "path" {
			keyed = append(keyed, p)
		}
	}
	switch method {
	case "post":
		if entity := entityOf(obj0(obj0(obj0(obj0(op["requestBody"])["content"])["application/json"])["schema"])); entity != "" && len(keyed) == 0 {
			g.create(at, id, entity)
		}
	case "get":
		if entity := entityOf(answer(op)); entity != "" && len(keyed) == 1 {
			g.read(at, id, entity)
		}
	case "put", "patch":
		if entity := entityOf(obj0(obj0(obj0(obj0(op["requestBody"])["content"])["application/json"])["schema"])); entity != "" && len(keyed) == 1 {
			g.update(at, id, entity, method == "patch")
		}
	}
}

// table is an operation's entity's table, or false when the operation is
// about an entity another stakeholder owns or one with no table.
func (g *gen) table(entity string) (gensql.Table, bool) {
	if g.owned.Covers(ownership.Entity("entities", entity)) {
		return gensql.Table{}, false
	}
	t, ok := g.tables[entity]
	return t, ok
}

// key is a table's primary key column, when the key is one field.
func key(t gensql.Table) (gensql.Column, bool) {
	var keys []gensql.Column
	for _, c := range t.Columns {
		if c.Key {
			keys = append(keys, c)
		}
	}
	if len(keys) != 1 {
		return gensql.Column{}, false
	}
	return keys[0], true
}

// create is the insert of a record: every column but the ones the database
// draws and the soft-delete flag, which keeps its default, answering the
// record as stored.
func (g *gen) create(at, id, entity string) {
	t, ok := g.table(entity)
	if !ok {
		return
	}
	var cols, values []string
	for _, c := range t.Columns {
		if c.Generated || c.Role == gensql.RoleDeleted {
			continue
		}
		cols = append(cols, c.Name)
		values = append(values, fmt.Sprintf("$%d", len(values)+1))
	}
	g.add(t, at, fmt.Sprintf("-- name: %s :one\nINSERT INTO %s (%s)\nVALUES (%s)\nRETURNING %s;\n", pascal(id), t.Name, strings.Join(cols, ", "), strings.Join(values, ", "), columns(t)))
}

// read is the select of one record by its key; a record deleted softly
// reads as not found.
func (g *gen) read(at, id, entity string) {
	t, ok := g.table(entity)
	if !ok {
		return
	}
	k, ok := key(t)
	if !ok {
		g.problem("warning", at, "%s reads %s by one path parameter, and the key of %s is not one field; the query is left to be written by hand", id, entity, t.Name)
		return
	}
	g.add(t, at, fmt.Sprintf("-- name: %s :one\nSELECT %s\nFROM %s\nWHERE %s = $1%s;\n", pascal(id), columns(t), t.Name, k.Name, notDeleted(t, "\n  AND ")))
}

// update is the change of one record by its key: every column a caller
// may set, and the audit columns of the change. A patch keeps a column the
// request leaves out.
func (g *gen) update(at, id, entity string, patch bool) {
	t, ok := g.table(entity)
	if !ok {
		return
	}
	k, ok := key(t)
	if !ok {
		g.problem("warning", at, "%s changes %s by one path parameter, and the key of %s is not one field; the query is left to be written by hand", id, entity, t.Name)
		return
	}
	var sets []string
	for _, c := range t.Columns {
		if c.Key || c.Generated || c.Role == gensql.RoleDeleted || c.Role == gensql.RoleCreated || c.ReadOnly && c.Role == "" {
			continue
		}
		switch {
		case patch && c.Role != gensql.RoleModified:
			sets = append(sets, fmt.Sprintf("%s = coalesce(sqlc.narg(%s), %s)", c.Name, c.Name, c.Name))
		default:
			sets = append(sets, fmt.Sprintf("%s = sqlc.arg(%s)", c.Name, c.Name))
		}
	}
	g.add(t, at, fmt.Sprintf("-- name: %s :one\nUPDATE %s\nSET %s\nWHERE %s = sqlc.arg(%s)%s\nRETURNING %s;\n", pascal(id), t.Name, strings.Join(sets, ",\n    "), k.Name, k.Name, notDeleted(t, "\n  AND "), columns(t)))
}

// list is a page of an entity's records with the operation's filters,
// search and sort, and the total that goes with it.
func (g *gen) list(at, path, id string, lo map[string]any, params []map[string]any) {
	entity := text(lo["entity"])
	if entity == "" {
		g.problem("warning", at+"/listOf", "%s lists the view %s, whose rows are a query of their own; the query is left to be written by hand", id, text(lo["view"]))
		return
	}
	t, ok := g.table(entity)
	if !ok {
		return
	}
	byField := map[string][]gensql.Column{}
	for _, c := range t.Columns {
		if c.Field != "" && c.Role == "" {
			byField[c.Field] = append(byField[c.Field], c)
		}
	}
	one := func(f string) (gensql.Column, bool) {
		cs := byField[f]
		if len(cs) != 1 {
			return gensql.Column{}, false
		}
		return cs[0], true
	}
	fieldNamed := map[string]string{}
	for f := range byField {
		fieldNamed[f] = f
		fieldNamed[wirename.Of(g.wire, f)] = f
	}
	type filter struct {
		col      gensql.Column
		required bool
	}
	var filters []filter
	seen := map[string]bool{}
	addFilter := func(f string, required bool) bool {
		c, ok := one(f)
		if !ok {
			return false
		}
		if !seen[c.Name] {
			seen[c.Name] = true
			filters = append(filters, filter{c, required})
		}
		return true
	}
	for _, p := range params {
		pn := text(p["name"])
		if text(p["in"]) == "path" {
			g.problem("warning", at+"/listOf", "%s lists %s under the path parameter %s, and a list under another record is not derived yet; the query is left to be written by hand", id, entity, pn)
			return
		}
		if text(p["in"]) != "query" {
			continue
		}
		f, ok := fieldNamed[pn]
		if !ok || !addFilter(f, p["required"] == true) {
			g.problem("warning", at+"/listOf", "%s takes the query parameter %s, which names no field of %s held in one column, so the query cannot tell what it filters; the query is left to be written by hand", id, pn, entity)
			return
		}
	}
	for _, f := range texts(list(lo["filterable"])) {
		if !addFilter(f, false) {
			g.problem("warning", at+"/listOf/filterable", "%s filters by %s, which is not held in one column of %s; the query is left to be written by hand", id, f, t.Name)
			return
		}
	}
	var search []gensql.Column
	for _, f := range texts(list(lo["searchable"])) {
		c, ok := one(f)
		if !ok {
			g.problem("warning", at+"/listOf/searchable", "%s searches %s, which is not held in one column of %s; the query is left to be written by hand", id, f, t.Name)
			return
		}
		search = append(search, c)
	}
	type sortKey struct {
		wire string
		col  gensql.Column
	}
	var sorts []sortKey
	for _, f := range texts(list(lo["sortable"])) {
		c, ok := one(f)
		if !ok {
			g.problem("warning", at+"/listOf/sortable", "%s sorts by %s, which is not held in one column of %s; the query is left to be written by hand", id, f, t.Name)
			return
		}
		sorts = append(sorts, sortKey{wirename.Of(g.wire, f), c})
	}

	var where []string
	for _, f := range filters {
		if f.required {
			where = append(where, fmt.Sprintf("%s = sqlc.arg(%s)", f.col.Name, f.col.Name))
			continue
		}
		where = append(where, fmt.Sprintf("(sqlc.narg(%s)::%s IS NULL OR %s = sqlc.narg(%s))", f.col.Name, f.col.Type, f.col.Name, f.col.Name))
	}
	if len(search) > 0 {
		var matches []string
		for _, c := range search {
			matches = append(matches, fmt.Sprintf("position(lower(sqlc.narg(search)) in lower(%s)) > 0", textOf(c)))
		}
		where = append(where, "(sqlc.narg(search)::text IS NULL\n       OR "+strings.Join(matches, "\n       OR ")+")")
	}
	if d := notDeleted(t, ""); d != "" {
		where = append(where, d)
	}
	cond := ""
	if len(where) > 0 {
		cond = "\nWHERE " + strings.Join(where, "\n  AND ")
	}
	var order []string
	for _, s := range sorts {
		order = append(order,
			fmt.Sprintf("CASE WHEN sqlc.arg(sort)::text = '%s' THEN %s END ASC", s.wire, s.col.Name),
			fmt.Sprintf("CASE WHEN sqlc.arg(sort)::text = '-%s' THEN %s END DESC", s.wire, s.col.Name))
	}
	for _, c := range t.Columns {
		if c.Key {
			order = append(order, c.Name)
		}
	}
	g.add(t, at, fmt.Sprintf("-- name: %s :many\nSELECT %s\nFROM %s%s\nORDER BY %s\nLIMIT sqlc.arg(page_size) OFFSET sqlc.arg(page_offset);\n\n-- name: %sTotal :one\nSELECT count(*) AS total\nFROM %s%s;\n",
		pascal(id), columns(t), t.Name, cond, strings.Join(order, ",\n    "), pascal(id), t.Name, cond))
}

// add puts a query in its table's file, below the marks of its operation.
func (g *gen) add(t gensql.Table, at, query string) {
	f := g.files[t.Name]
	if f == nil {
		f = &file{entity: t.Entity}
		g.files[t.Name] = f
	}
	f.queries = append(f.queries, g.marks(at)+query)
}

// columns are a table's columns in the order the migration creates them.
func columns(t gensql.Table) string {
	var out []string
	for _, c := range t.Columns {
		out = append(out, c.Name)
	}
	return strings.Join(out, ", ")
}

// notDeleted is the condition that leaves a softly deleted record out, after
// the joiner, or "" for a table with no flag.
func notDeleted(t gensql.Table, joiner string) string {
	for _, c := range t.Columns {
		if c.Role == gensql.RoleDeleted {
			return joiner + c.Name + " = false"
		}
	}
	return ""
}

// textOf is a column as text for a search.
func textOf(c gensql.Column) string {
	upper := strings.ToUpper(c.Type)
	for _, t := range []string{"VARCHAR", "CHAR", "TEXT", "CHARACTER"} {
		if strings.HasPrefix(upper, t) {
			return c.Name
		}
	}
	return c.Name + "::text"
}

// parameters are an operation's parameters and its path's, the
// operation's taking the place of a path's of the same name and place.
func parameters(item, op map[string]any) []map[string]any {
	var out []map[string]any
	own := map[string]bool{}
	for _, p := range list(op["parameters"]) {
		pm := obj0(p)
		own[text(pm["in"])+" "+text(pm["name"])] = true
		out = append(out, pm)
	}
	for _, p := range list(item["parameters"]) {
		pm := obj0(p)
		if !own[text(pm["in"])+" "+text(pm["name"])] {
			out = append(out, pm)
		}
	}
	return out
}

// answer is the schema of an operation's 200 answer.
func answer(op map[string]any) map[string]any {
	return obj0(obj0(obj0(obj0(obj0(op["responses"])["200"])["content"])["application/json"])["schema"])
}

// entityOf is the entity a schema names by $ref, or "".
func entityOf(schema map[string]any) string {
	e, _ := strings.CutPrefix(text(schema["$ref"]), "#/entities/")
	if strings.Contains(e, "/") {
		return ""
	}
	return e
}

// pascal is an operationId as the query's name: registerMember is
// RegisterMember, the name sqlc gives the Go method.
func pascal(id string) string {
	if id == "" {
		return id
	}
	return strings.ToUpper(id[:1]) + id[1:]
}

// place places the request's problems at the entities and operations the
// queries show (internal/mark).
func (g *gen) place(r *Request) {
	var elements []string
	for name := range g.tables {
		elements = append(elements, "/entities/"+mark.Escape(name))
	}
	for p, item := range obj0(g.spec["paths"]) {
		for _, m := range []string{"get", "put", "patch", "post"} {
			if obj0(obj0(item)[m]) != nil {
				elements = append(elements, "/paths/"+mark.Escape(p)+"/"+m)
			}
		}
	}
	sort.Strings(elements)
	g.placed = mark.Place(r.Problems, elements, []string{"/entities", "/paths"})
}

// marks are the comment lines of the problems placed at an element.
func (g *gen) marks(ptr string) string {
	var b strings.Builder
	for _, p := range g.placed[ptr] {
		b.WriteString("-- " + mark.Line(p) + "\n")
	}
	return b.String()
}

// handWritten refuses to write over a file in the output folder that this
// plug-in did not write: a file written by hand is never touched.
func (g *gen) handWritten(files, existing []gensql.File) bool {
	have := map[string]string{}
	for _, f := range existing {
		have[f.Path] = f.Content
	}
	found := false
	for _, f := range files {
		if content, ok := have[f.Path]; ok && !strings.HasPrefix(content, "-- Generated by "+name+" ") {
			g.problem("error", "/", "%s is in the output folder and was not written by %s, so it is left as it is and nothing is written; compare it with generate --check, move it, or delete it to have it generated", f.Path, name)
			found = true
		}
	}
	return found
}

func (g *gen) problem(severity, path, format string, args ...any) {
	g.diags = append(g.diags, gensql.Diagnostic{File: g.root, Line: 1, Severity: severity, Path: path, Rule: "generator", Message: fmt.Sprintf(format, args...)})
}

func (g *gen) response(files []gensql.File) gensql.Response {
	if files == nil {
		files = []gensql.File{}
	}
	diags := g.diags
	if diags == nil {
		diags = []gensql.Diagnostic{}
	}
	return gensql.Response{Files: files, Diagnostics: diags}
}

// relRoot is the root file's path as seen from the output folder.
func relRoot(root, output string) string {
	return gensql.RelRoot(root, output)
}

func obj(v any) (map[string]any, bool) {
	m, ok := v.(map[string]any)
	return m, ok
}

func obj0(v any) map[string]any {
	m, _ := v.(map[string]any)
	return m
}

func list(v any) []any {
	l, _ := v.([]any)
	return l
}

func texts(l []any) []string {
	var out []string
	for _, v := range l {
		out = append(out, text(v))
	}
	return out
}

func text(v any) string {
	s, _ := v.(string)
	return s
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
