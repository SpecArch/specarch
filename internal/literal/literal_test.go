package literal

import (
	"strings"
	"testing"
)

const generated = `// Generated by a plug-in. Do not edit this file.
import type { ListPageSchema } from "@/screens";

export const schema = {
  title: "members-list.title",
  pageSize: 20,
  columns: [
    { field: "fullName", sortable: true },
    { field: "email", sortable: false },
  ],
  "row-actions": [],
  failed: null,
} satisfies ListPageSchema;
`

func TestFormattingDoesNotCount(t *testing.T) {
	hand := `import type {ListPageSchema} from '@/screens'
;
/* written by hand */
export const schema = {
  "title": 'members-list.title', pageSize: 2.0e1,
  columns: [{ field: "fullName", sortable: true }, { field: "email", sortable: false }],
  failed: null, 'row-actions': [],
} satisfies ListPageSchema
`
	if d := compare(t, hand, generated); len(d) != 0 {
		t.Fatalf("want no difference, got %v", d)
	}
}

func TestAChangedColumnIsNamed(t *testing.T) {
	hand := strings.Replace(generated, `field: "email", sortable: false`, `field: "email", sortable: true`, 1)
	d := compare(t, hand, generated)
	if len(d) != 1 || d[0].String() != "columns[1].sortable: true on disk; generate writes false" {
		t.Fatalf("got %v", d)
	}
}

func TestKeysAndItemsOnOneSide(t *testing.T) {
	hand := strings.Replace(generated, `  pageSize: 20,`+"\n", `  extra: "x",`+"\n", 1)
	hand = strings.Replace(hand, `    { field: "email", sortable: false },`+"\n", "", 1)
	var got []string
	for _, d := range compare(t, hand, generated) {
		got = append(got, d.String())
	}
	want := []string{
		"pageSize: not on disk; generate writes 20",
		`columns[1]: not on disk; generate writes {"field": "email", "sortable": false}`,
		`extra: "x" on disk; generate writes nothing there`,
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("got\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

func TestOutsideTheSubset(t *testing.T) {
	for _, tc := range []struct{ src, want string }{
		{"export const schema = { onSave: save };", "line 1: the name save is a reference, not data; the subset holds only literals"},
		{"export const schema = { title: `x` };", "line 1: '`' is outside the object-literal subset"},
		{"import x from \"y\";\nconst a = 1;", `line 2: found "const"; the subset holds import statements and one export const of an object literal`},
		{"export const schema = { a: 1, a: 2 };", `line 1: the key "a" is given twice`},
		{"export const schema = { a: 0x1F };", "line 1: expected \"}\", found \"x1F\""},
		{"import x from \"y\";", "line 1: no export const of an object literal"},
	} {
		_, err := Parse([]byte(tc.src))
		if err == nil || err.Error() != tc.want {
			t.Errorf("%s: got %v, want %s", tc.src, err, tc.want)
		}
	}
}

func compare(t *testing.T, disk, gen string) []Difference {
	t.Helper()
	d, err := Parse([]byte(disk))
	if err != nil {
		t.Fatalf("disk: %v", err)
	}
	g, err := Parse([]byte(gen))
	if err != nil {
		t.Fatalf("generated: %v", err)
	}
	return Compare(d, g)
}
