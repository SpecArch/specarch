var bookmarkName = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]{0,39}$`)

// checkPackage checks a package as TestStructure says.
func checkPackage(t *testing.T, data []byte) {
	t.Helper()
	z, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		t.Fatalf("the package is not a zip: %v", err)
	}
	if z.File[0].Name != "[Content_Types].xml" {
		t.Errorf("the first entry is %s, not [Content_Types].xml", z.File[0].Name)
	}
	for _, f := range z.File {
		if !f.Modified.Equal(time.Date(1980, 1, 1, 0, 0, 0, 0, time.UTC)) {
			t.Errorf("%s is dated %v, not 1980-01-01", f.Name, f.Modified)
		}
	}
	parts := readParts(t, data)
	for name, text := range parts {
		d := xml.NewDecoder(strings.NewReader(text))
		for {
			if _, err := d.Token(); err == io.EOF {
				break
			} else if err != nil {
				t.Fatalf("%s is not well-formed XML: %v", name, err)
			}
		}
	}

	// Content types: every part has one.
	var types struct {
		Defaults []struct {
			Ext string `xml:"Extension,attr"`
		} `xml:"Default"`
		Overrides []struct {
			Part string `xml:"PartName,attr"`
			Type string `xml:"ContentType,attr"`
		} `xml:"Override"`
	}
	unmarshal(t, parts["[Content_Types].xml"], &types)
	typed := map[string]bool{}
	for _, o := range types.Overrides {
		typed[strings.TrimPrefix(o.Part, "/")] = true
		if _, ok := parts[strings.TrimPrefix(o.Part, "/")]; !ok {
			t.Errorf("[Content_Types].xml types %s, which the package does not hold", o.Part)
		}
	}
	for name := range parts {
		if name == "[Content_Types].xml" || typed[name] {
			continue
		}
		ok := false
		for _, d := range types.Defaults {
			if strings.HasSuffix(name, "."+d.Ext) && d.Ext == "rels" {
				ok = true
			}
		}
		if !ok {
			t.Errorf("%s has no content type of its own", name)
		}
	}

	// Relationships: every internal target is a part.
	docRels := map[string]bool{}
	for name, text := range parts {
		if !strings.HasSuffix(name, ".rels") {
			continue
		}
		var rels struct {
			Items []struct {
				ID     string `xml:"Id,attr"`
				Target string `xml:"Target,attr"`
				Mode   string `xml:"TargetMode,attr"`
			} `xml:"Relationship"`
		}
		unmarshal(t, text, &rels)
		dir := filepath.ToSlash(filepath.Dir(filepath.Dir(name)))
		for _, r := range rels.Items {
			if name == "word/_rels/document.xml.rels" {
				docRels[r.ID] = true
			}
			if r.Mode == "External" {
				continue
			}
			target := filepath.ToSlash(filepath.Join(dir, r.Target))
			if _, ok := parts[strings.TrimPrefix(target, "./")]; !ok {
				t.Errorf("%s names %s (%s), which the package does not hold", name, r.Target, target)
			}
		}
	}

	styles := ids(t, parts["word/styles.xml"], "style", "styleId")
	nums := ids(t, parts["word/numbering.xml"], "num", "numId")
	for _, name := range []string{"word/document.xml", "word/styles.xml", "word/numbering.xml", "word/settings.xml", "word/header1.xml", "word/footer1.xml", "word/fontTable.xml"} {
		checkXML(t, name, parts[name], styles, nums, docRels)
	}
}

func unmarshal(t *testing.T, text string, v any) {
	t.Helper()
	if err := xml.Unmarshal([]byte(text), v); err != nil {
		t.Fatal(err)
	}
}

// ids are the values of attr on the elements named el.
func ids(t *testing.T, text, el, attr string) map[string]bool {
	out := map[string]bool{}
	d := xml.NewDecoder(strings.NewReader(text))
	for {
		tok, err := d.Token()
		if err != nil {
			return out
		}
		if s, ok := tok.(xml.StartElement); ok && s.Name.Local == el {
			for _, a := range s.Attr {
				if a.Name.Local == attr {
					out[a.Value] = true
				}
			}
		}
	}
}

type node struct {
	name     string
	children []string
	cells    int // for a row: its cells; for a table: its grid's columns
	rows     []int
	hasP     bool
}

// checkXML walks one part, checking the order of children, the tables, the
// body's last element and every reference.
func checkXML(t *testing.T, part, text string, styles, nums, rels map[string]bool) {
	t.Helper()
	d := xml.NewDecoder(strings.NewReader(text))
	var stack []*node
	bookmarks := map[string]bool{}
	open := map[string]bool{}
	var anchors []string
	for {
		tok, err := d.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatalf("%s: %v", part, err)
		}
		switch x := tok.(type) {
		case xml.StartElement:
			name := x.Name.Local
			if len(stack) > 0 {
				parent := stack[len(stack)-1]
				parent.children = append(parent.children, name)
				switch {
				case parent.name == "tblGrid" && name == "gridCol":
					stack[len(stack)-2].cells++
				case parent.name == "tr" && name == "tc":
					parent.cells++
				case parent.name == "tc" && name == "p":
					parent.hasP = true
				}
			}
			attr := func(local string) string {
				for _, a := range x.Attr {
					if a.Name.Local == local {
						return a.Value
					}
				}
				return ""
			}
			switch name {
			case "pStyle", "rStyle", "tblStyle", "basedOn", "next":
				if v := attr("val"); !styles[v] {
					t.Errorf("%s: %s names style %s, which styles.xml does not define", part, name, v)
				}
			case "numId":
				if v := attr("val"); stack[len(stack)-1].name == "numPr" && !nums[v] {
					t.Errorf("%s: numId %s is not a num of numbering.xml", part, v)
				}
			case "bookmarkStart":
				n, id := attr("name"), attr("id")
				if !bookmarkName.MatchString(n) {
					t.Errorf("%s: bookmark name %q is not one Word accepts", part, n)
				}
				if bookmarks[n] {
					t.Errorf("%s: bookmark %s twice", part, n)
				}
				bookmarks[n] = true
				if open[id] {
					t.Errorf("%s: bookmark id %s opened twice", part, id)
				}
				open[id] = true
			case "bookmarkEnd":
				if !open[attr("id")] {
					t.Errorf("%s: bookmark id %s ends without a start", part, attr("id"))
				}
				delete(open, attr("id"))
			case "hyperlink":
				for _, up := range stack {
					if up.name == "hyperlink" {
						t.Errorf("%s: a hyperlink inside another hyperlink", part)
					}
				}
				if a := attr("anchor"); a != "" {
					anchors = append(anchors, a)
				} else if !rels[attr("id")] {
					t.Errorf("%s: hyperlink r:id %q has no relationship", part, attr("id"))
				}
			case "headerReference", "footerReference":
				if !rels[attr("id")] {
					t.Errorf("%s: %s r:id %q has no relationship", part, name, attr("id"))
				}
			}
			stack = append(stack, &node{name: name})
		case xml.EndElement:
			n := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			checkOrder(t, part, n)
			switch n.name {
			case "tc":
				if !n.hasP {
					t.Errorf("%s: a table cell holds no paragraph", part)
				}
			case "tr":
				stack[len(stack)-1].rows = append(stack[len(stack)-1].rows, n.cells)
			case "tbl":
				for _, c := range n.rows {
					if c != n.cells {
						t.Errorf("%s: a row of %d cells in a table whose grid has %d columns", part, c, n.cells)
					}
				}
			case "body":
				if len(n.children) == 0 || n.children[len(n.children)-1] != "sectPr" {
					t.Errorf("%s: the body does not end with sectPr", part)
				}
				for i := 1; i < len(n.children); i++ {
					if n.children[i] == "tbl" && n.children[i-1] == "tbl" {
						t.Errorf("%s: two tables with no paragraph between them, which Word joins into one", part)
					}
				}
			}
		}
	}
	if len(open) > 0 {
		t.Errorf("%s: %d bookmarks never end", part, len(open))
	}
	for _, a := range anchors {
		if !bookmarks[a] {
			t.Errorf("%s: a link to bookmark %s, which the document does not have", part, a)
		}
	}
}

func checkOrder(t *testing.T, part string, n *node) {
	order, ok := childOrder[n.name]
	if !ok {
		return
	}
	at := map[string]int{}
	for i, names := range order {
		for _, name := range strings.Split(names, "|") {
			at[name] = i
		}
	}
	last := -1
	for _, c := range n.children {
		i, ok := at[c]
		if !ok {
			t.Errorf("%s: %s may not hold %s", part, n.name, c)
			continue
		}
		if i < last {
			t.Errorf("%s: %s holds %s after %s, out of the schema's order (%v)", part, n.name, c, order[last], n.children)
		}
		last = max(last, i)
	}
}
