// recordDocuments are the targets made from the records beside the
// specification rather than from the specification: never drafts, and not
// outputs of the specification in the open questions document.
var recordDocuments = map[string]bool{"changes": true, "releases": true, "communications": true, "timeline": true, "testruns": true, "progress": true}

// newRecordDoc starts a document made from the records, with a header that
// names the root file, its version, the records folder and the meta-model.
func newRecordDoc(target string, root *yaml.Node, relRoot string, state *State) *doc {
	d := &doc{sources: get(root, "sources"), decisions: get(root, "decisions"), questions: questionsOf(root), pointerOf: pointers(root), unconfirmedStakeholders: validate.StakeholdersUnconfirmed(root)}
	d.line(tr("<!-- Generated by specarch document %s from %s, version %s, and the records in %s/; meta-model %s. Do not edit this file: change the YAML and generate again. -->"),
		target, relRoot, str(get(root, "info"), "version"), state.RecordsRel, str(root, "specarch"))
	d.blank()
	return d
}

// recordsOf lists the records of one kind, in ID order.
func recordsOf(state *State, kind string) []*yaml.Node {
	var out []*yaml.Node
	for _, r := range state.Records {
		if str(r, "kind") == kind {
			out = append(out, r)
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return idLess(str(out[i], "id"), str(out[j], "id")) })
	return out
}

// groupOrder places each status in the register: open first, then done,
// then closed without a change.
var groupOrder = map[string]int{
	"proposed": 0, "analysed": 0, "approved": 0, "implemented": 1, "released": 1, "rejected": 2, "withdrawn": 2,
	"reported": 0, "confirmed": 0, "fixed": 1, "not-a-defect": 2, "duplicate": 2,
}

func byGroup(rs []*yaml.Node) []*yaml.Node {
	out := append([]*yaml.Node{}, rs...)
	sort.SliceStable(out, func(i, j int) bool { return groupOrder[str(out[i], "status")] < groupOrder[str(out[j], "status")] })
	return out
}

func isOpen(r *yaml.Node) bool { return groupOrder[str(r, "status")] == 0 }

// refList writes requirement IDs plain and #/ pointers as code.
func refList(refs []string) string {
	out := make([]string, len(refs))
	for i, r := range refs {
		if strings.HasPrefix(r, "#/") {
			out[i] = "`" + r + "`"
		} else {
			out[i] = r
		}
	}
	return strings.Join(out, ", ")
}

func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" || strings.HasSuffix(s, ".") {
		return s
	}
	return s + "."
}

// Changes writes the change and defect register from the records.
func Changes(root *yaml.Node, relRoot string, impls []Implementation, state *State) string {
	d := newRecordDoc("changes", root, relRoot, state)
	reachOf := map[string]openChange{}
	for _, c := range openChangesOf(state) {
		reachOf[c.id] = c
	}
	info := get(root, "info")
	changes, defects := recordsOf(state, "change"), recordsOf(state, "defect")
	open := 0
	for _, r := range append(append([]*yaml.Node{}, changes...), defects...) {
		if isOpen(r) {
			open++
		}
	}
	d.line(tr("# %s: change and defect register"), str(info, "title"))
	d.blank()
	d.para(fmt.Sprintf(tr("Version %s of the specification: %s and %s are recorded beside it, %s open. Open items come first, then the ones carried out, then the ones closed without a change. The register is made from the records in `records/changes/` and `records/defects/`: they say what was asked and decided, and the specification says what is true now. Under each open change request stands what it reaches in the specification as it is now, before anything changes."),
		str(info, "version"), countText(len(changes), tr("change request"), tr("change requests")), countText(len(defects), tr("defect"), tr("defects")), countText(open, tr("item"), tr("items"))))
	d.stakeholdersNotice()

	d.section(tr("Change requests"))
	if len(changes) == 0 {
		d.para(tr("No change request is recorded."))
	} else {
		changes = byGroup(changes)
		d.line(tr("| Change | Title | Status | Raised in | Type | Urgency | Impact | Cause | Release |"))
		d.line("|---|---|---|---|---|---|---|---|---|")
		for _, c := range changes {
			d.line("| %s | %s | %s | %s | %s | %s | %s | %s | %s |", str(c, "id"), cell(str(c, "title")), str(c, "status"), str(c, "phase"), str(c, "type"), str(c, "urgency"), cell(str(c, "impact")), cell(str(c, "cause")), cell(str(c, "release")))
		}
		d.blank()
		for _, c := range changes {
			d.heading(3, str(c, "id")+": "+str(c, "title"))
			d.para(fmt.Sprintf(tr("Raised by %s on %s, in %s. %s, %s urgency%s. Status: %s."),
				str(c, "raisedBy"), str(c, "raised"), str(c, "phase"), capitalise(str(c, "type")), str(c, "urgency"), impactText(str(c, "impact")), str(c, "status")))
			d.remark(c)
			d.para(str(c, "reason"))
			if cause := str(c, "cause"); cause != "" {
				d.para(tr("Cause: ") + cause + causeMeaning(cause) + ".")
			}
			if qs := strs(c, "questions"); len(qs) > 0 {
				d.para(tr("The analysis raised ") + oneOrMany(len(qs), tr("the question"), tr("the questions")) + " " + strings.Join(qs, ", ") + ".")
			}
			affects := get(c, "affects")
			var parts []string
			for _, list := range []struct{ key, verb string }{{"adds", tr("adds")}, {"changes", tr("changes")}, {"removes", tr("removes")}} {
				if refs := strs(affects, list.key); len(refs) > 0 {
					parts = append(parts, list.verb+" "+refList(refs))
				}
			}
			if len(parts) > 0 {
				d.para(tr("Affects: ") + strings.Join(parts, "; ") + ".")
			}
			if dec := get(c, "decision"); dec != nil {
				d.para(fmt.Sprintf(tr("Decision: %s by %s on %s. %s"), str(dec, "outcome"), str(dec, "by"), str(dec, "date"), sentence(str(dec, "why"))))
			}
			if rel := str(c, "release"); rel != "" {
				d.para(tr("Released in ") + rel + ".")
			}
			if oc, ok := reachOf[str(c, "id")]; ok {
				d.reach(root, impls, state, oc)
			}
		}
	}

	d.section(tr("Defects"))
	if len(defects) == 0 {
		d.para(tr("No defect is recorded."))
	} else {
		defects = byGroup(defects)
		d.line(tr("| Defect | Title | Status | Severity | Found in | Violates | Test |"))
		d.line("|---|---|---|---|---|---|---|")
		for _, f := range defects {
			d.line("| %s | %s | %s | %s | %s | %s | %s |", str(f, "id"), cell(str(f, "title")), str(f, "status"), str(f, "severity"), foundIn(f), cell(refList(strs(f, "violates"))), cell(str(f, "test")))
		}
		d.blank()
		for _, f := range defects {
			d.heading(3, str(f, "id")+": "+str(f, "title"))
			where := tr("during ") + str(f, "phase")
			if env := str(f, "environment"); env != "" {
				where = tr("in ") + str(f, "phase") + tr(", on the ") + env + tr(" environment")
			}
			d.para(fmt.Sprintf(tr("Reported by %s on %s, %s. Severity %s. Status: %s."), str(f, "reportedBy"), str(f, "reported"), where, str(f, "severity"), str(f, "status")))
			d.remark(f)
			var lines []string
			if v := strs(f, "violates"); len(v) > 0 {
				lines = append(lines, tr("Violates ")+refList(v)+".")
			}
			if t := str(f, "test"); t != "" {
				lines = append(lines, tr("The test ")+t+tr(" shows it fixed."))
			}
			if inc := strs(f, "incidents"); len(inc) > 0 {
				lines = append(lines, tr("Caused ")+strings.Join(inc, ", ")+".")
			}
			if dup := str(f, "duplicateOf"); dup != "" {
				lines = append(lines, tr("A duplicate of ")+dup+".")
			}
			if ch := str(f, "change"); ch != "" {
				lines = append(lines, tr("Not a defect; it became the change request ")+ch+".")
			}
			if rel := str(f, "release"); rel != "" {
				lines = append(lines, tr("Fixed in ")+rel+".")
			}
			d.para(strings.Join(lines, " "))
		}
	}

	// A workflow that keeps its as-is beside the to-be while a business
	// process changes: what moving to the to-be reaches (ADR-236). Left
	// out when none does, so a register without one reads as before.
	if ts := transition.Of(root); len(ts) > 0 {
		d.section(tr("Transitions"))
		d.para(fmt.Sprintf(tr("%s the as-is beside the to-be while the business process changes. Under each stands what moving from the as-is to the to-be adds, changes and removes, from the specification as it is now: the workflow's trigger, subject and messages, its steps, the roles that approve them or do their tasks, the operations it calls, and the pages and tests that rest on it. The generators write the to-be, and the as-is with `specarch generate --as-is`."),
			oneOrMany(len(ts), tr("One workflow keeps"), fmt.Sprintf(tr("%d workflows keep"), len(ts)))))
		for _, tn := range ts {
			d.heading(3, tr("Workflow ")+tn.Workflow)
			for _, part := range tn.Parts {
				d.line("- %s: %s.", capitalise(part.Name), strings.Join(part.Items, "; "))
			}
			d.blank()
		}
	}
	return d.String()
}

// raisedIn says where a change or defect was raised and by which role,
// for the release notes: "; raised in acceptance by librarian".
func raisedIn(x *yaml.Node, byKey string) string {
	phase := str(x, "phase")
	if phase == "" {
		return ""
	}
	out := tr("; raised in ") + phase
	if by := str(x, byKey); by != "" {
		out += tr(" by ") + by
	}
	return out
}

// causeText names a change's cause for the release notes, with what the
// value means, or "" when none is written.
func causeText(cause string) string {
	meaning := map[string]string{
		"omitted": tr("the specification left it out"),
		"wrong":   tr("the specification said it wrongly"),
		"changed": tr("the need changed after it was written"),
		"unheard": tr("the stakeholder who uses it was not asked"),
	}[cause]
	if meaning == "" {
		return ""
	}
	return tr("; cause ") + cause + " (" + meaning + ")"
}

// remark writes what a change or defect from acceptance carries about the
// build it was seen on: the build, where it was seen, and what was
// observed and expected.
func (d *doc) remark(r *yaml.Node) {
	if against := get(r, "against"); against != nil {
		line := tr("Against the build of version ") + str(against, "version")
		if env := str(against, "environment"); env != "" {
			line += tr(" on ") + env
		}
		var more []string
		if b := str(against, "build"); b != "" {
			more = append(more, tr("build ")+b)
		}
		if dg := str(against, "digest"); dg != "" {
			more = append(more, tr("digest `")+dg+"`")
		}
		if len(more) > 0 {
			line += " (" + strings.Join(more, ", ") + ")"
		}
		d.para(line + ".")
	}
	if seen := strs(r, "seenAt"); len(seen) > 0 {
		d.para(tr("Seen at ") + refList(seen) + ".")
	}
	if o := str(r, "observed"); o != "" {
		d.para(tr("Observed: ") + sentence(o) + tr(" Expected: ") + sentence(str(r, "expected")))
	}
}

// oneOrMany is one or many by the count, without the number.
func oneOrMany(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}

// causeMeaning is what a cause value means, in parentheses.
func causeMeaning(cause string) string {
	if m := causeText(cause); m != "" {
		return m[strings.Index(m, " ("):]
	}
	return ""
}

// foundIn is where a defect was found: its environment, or its phase
// when it names none.
func foundIn(f *yaml.Node) string {
	if env := str(f, "environment"); env != "" {
		return env
	}
	return str(f, "phase")
}

func impactText(impact string) string {
	if impact == "" {
		return ""
	}
	return tr("; impact ") + impact
}

func capitalise(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// Releases writes the release notes from the records, newest first.
func Releases(root *yaml.Node, relRoot string, state *State) string {
	d := newRecordDoc("releases", root, relRoot, state)
	info := get(root, "info")
	releases := recordsOf(state, "release")
	sort.SliceStable(releases, func(i, j int) bool {
		a, _ := semver.Parse(str(releases[i], "version"))
		b, _ := semver.Parse(str(releases[j], "version"))
		return semver.Compare(a, b) > 0
	})
	byID := map[string]*yaml.Node{}
	for _, r := range state.Records {
		if k := str(r, "kind"); k == "change" || k == "defect" {
			byID[str(r, "id")] = r
		}
	}
	d.line(tr("# %s: release notes"), str(info, "title"))
	d.blank()
	d.para(fmt.Sprintf(tr("Version %s of the specification: %s recorded beside it, newest first. Each lists what it includes, grouped as added, changed, removed and fixed, from the change and defect records in `records/`, each change with where it was raised and why the result was not what was wanted, and the changes counted by cause: omitted, wrong and unheard measure the requirements work, changed is normal change."),
		str(info, "version"), countText(len(releases), tr("release is"), tr("releases are"))))
	d.stakeholdersNotice()
	if len(releases) == 0 {
		d.para(tr("No release is recorded."))
	}
	for _, r := range releases {
		title := str(r, "version") + ", " + str(r, "status")
		if date := str(r, "date"); date != "" {
			title += " " + date
		}
		d.heading(2, title)
		groups := map[string][]string{}
		var tracker []string
		byCause := map[string]int{}
		changesCounted := 0
		for _, id := range strs(r, "includes") {
			x := byID[id]
			if x == nil {
				tracker = append(tracker, id)
				continue
			}
			name := id + ", " + str(x, "title")
			if str(x, "kind") == "defect" {
				groups["Fixed"] = append(groups["Fixed"], name+tr(": violated ")+refList(strs(x, "violates"))+raisedIn(x, "reportedBy")+".")
				continue
			}
			changesCounted++
			if cause := str(x, "cause"); cause != "" {
				byCause[cause]++
			}
			affects := get(x, "affects")
			for _, g := range []struct{ key, title string }{{"adds", "Added"}, {"changes", "Changed"}, {"removes", "Removed"}} {
				if refs := strs(affects, g.key); len(refs) > 0 {
					groups[g.title] = append(groups[g.title], name+": "+refList(refs)+raisedIn(x, "raisedBy")+causeText(str(x, "cause"))+".")
				}
			}
		}
		if len(groups) == 0 && len(tracker) == 0 {
			d.para(tr("Includes no recorded change or defect."))
		}
		for _, g := range []string{"Added", "Changed", "Removed", "Fixed"} {
			if len(groups[g]) == 0 {
				continue
			}
			d.heading(3, tr(g))
			for _, item := range groups[g] {
				d.line("- %s", item)
			}
			d.blank()
		}
		if len(tracker) > 0 {
			d.para(tr("Also includes, kept in a tracker: ") + strings.Join(tracker, ", ") + ".")
		}
		if changesCounted > 0 {
			var parts []string
			for _, c := range []string{"omitted", "wrong", "changed", "unheard"} {
				if byCause[c] > 0 {
					parts = append(parts, fmt.Sprintf("%d %s", byCause[c], c))
				}
			}
			if unsaid := changesCounted - (byCause["omitted"] + byCause["wrong"] + byCause["changed"] + byCause["unheard"]); unsaid > 0 {
				parts = append(parts, fmt.Sprintf(tr("%d with no cause written"), unsaid))
			}
			d.para(tr("Changes by cause: ") + strings.Join(parts, ", ") + ".")
		}
		var facts []string
		if v := str(r, "specificationVersion"); v != "" {
			facts = append(facts, tr("Specification ")+v+".")
		}
		if impls := pairs(r, "implementations"); len(impls) > 0 {
			var parts []string
			for _, p := range impls {
				parts = append(parts, p.Key.Value+" "+p.Value.Value)
			}
			facts = append(facts, tr("Implementations: ")+strings.Join(parts, ", ")+".")
		}
		if runs := strs(r, "commissioning"); len(runs) > 0 {
			run := tr("run ")
			if len(runs) > 1 {
				run = tr("runs ")
			}
			facts = append(facts, tr("Accepted by the commissioning ")+run+strings.Join(runs, ", ")+".")
		}
		if c := str(r, "commit"); c != "" {
			facts = append(facts, tr("Built from commit ")+c+".")
		}
		d.para(strings.Join(facts, " "))
	}
	return d.String()
}
