// The two files the Dart plug-in writes in the target's folder: the
// values, the harness and the checks, which the project's harness file
// imports too, and the tests.
const (
	DartLibraryFile = "specarch_design.dart"
	DartTestFile    = "specarch_design_test.dart"
	DartHarnessFile = "specarch_harness.dart" // written by the project
)

// dartFrameworks are the testing frameworks the Dart plug-in writes for,
// each with the library its tests import. Both have the same test and fail,
// so only the import differs: package:test for Dart, flutter_test for a
// Flutter app, whose widget tests need its binding.
var dartFrameworks = map[string]string{
	"package:test": "package:test/test.dart",
	"flutter_test": "package:flutter_test/flutter_test.dart",
}

// GenerateDart writes the Dart tests of a request: the tests and the
// library of values, harness and checks they and the project's harness
// share.
func GenerateDart(r *Request) Response {
	f, refused := framework(r, "specarch-gen-tests-dart", "package:test", "flutter_test")
	if refused != nil {
		return *refused
	}
	if f == "" {
		f = "package:test"
	}
	imp := dartFrameworks[f]
	s := Build(r)
	header := fmt.Sprintf("// Code generated by specarch-gen-tests-dart from %s, version %s, meta-model %s. DO NOT EDIT.", s.Root, s.Version, s.Meta)

	lib := &writer{}
	lib.line("%s", header)
	lib.line("")
	lib.line("// The values, the harness and the checks the design tests of %s use.", s.Title)
	lib.line("// The project's %s imports it too, to give newHarness.", DartHarnessFile)
	lib.line("")
	lib.line("import '%s';", imp)
	lib.line("")
	lib.b.WriteString(dartPrelude + "\n")

	w := &writer{}
	w.line("%s", header)
	w.line("")
	w.line("// The design tests and worked examples of %s, run through the", s.Title)
	w.line("// Harness the project gives them in newHarness, in %s.", DartHarnessFile)
	w.line("")
	w.line("import '%s';", imp)
	w.line("")
	w.line("import '%s';", DartLibraryFile)
	w.line("import '%s';", DartHarnessFile)
	w.line("")
	w.line("void main() {")
	first := true
	for _, t := range s.Tests {
		if !first {
			w.line("")
		}
		first = false
		dartTest(w, t)
	}
	for _, a := range s.Algorithms {
		if !first {
			w.line("")
		}
		first = false
		dartAlgorithm(w, a)
	}
	w.line("}")
	return Response{Files: []File{{Path: DartLibraryFile, Content: lib.b.String()}, {Path: DartTestFile, Content: w.b.String()}}, Diagnostics: []Diagnostic{}}
}

func dartTest(w *writer, t Test) {
	if t.NotApplicable != "" {
		w.line("  // %s is not applicable: %s", t.Name, t.NotApplicable)
		return
	}
	w.line("  test(%s, () async {", dartString(t.Name+": "+t.Subject+", "+t.Scenario+" scenario"))
	w.line("    // Given %s", t.Given)
	w.line("    // When %s", t.When)
	w.line("    // Then %s", t.Then)
	w.line("    final h = await newHarness();")
	if t.Caller != "" {
		w.line("    await h.signIn(%s);", dartString(t.Caller))
	}
	for _, s := range t.Inserts {
		w.line("    await h.insert(%s, %s);", dartString(s.Mapping), dartRecord(s.Record))
	}
	c := t.Call
	if c == nil {
		w.line("    await body%s(h); // written by hand in %s: the design gives no call to make", pascal(t.Name), DartHarnessFile)
		w.line("  });")
		return
	}
	got := "final got = "
	if !t.Expect.Checked() {
		got = ""
	}
	switch c.Kind {
	case "request":
		w.line("    %sawait h.request(%s, %s, %s, %s);", got, dartString(c.Mapping), dartString(c.Method), dartString(c.Path), dartRecord(c.Input))
	case "run":
		var parts []string
		for _, a := range c.Arguments {
			var vs []string
			for _, v := range a.Values {
				vs = append(vs, dartValue(v))
			}
			parts = append(parts, fmt.Sprintf("%s: [%s]", dartString(a.Name), strings.Join(vs, ", ")))
		}
		w.line("    %sawait h.run(%s, %s, {%s}, %s);", got, dartString(c.Mapping), dartString(c.Command), strings.Join(parts, ", "), dartRecord(c.Options))
	case "open":
		w.line("    %sawait h.open(%s, %s, %s, %s);", got, dartString(c.Mapping), dartString(c.Page), dartString(c.Route), dartRecord(c.Input))
	}
	e := t.Expect
	if e.Status != "" {
		w.line("    expectStatus(got, %s);", e.Status)
	}
	if e.HasBody {
		w.line("    expectBody(got, %s);", dartRecord(e.Body))
	}
	if e.Exit != "" {
		w.line("    expectExit(got, %s);", e.Exit)
	}
	if e.HasOutput {
		w.line("    expectOutput(got, %s);", dartStrings(e.Output))
	}
	for _, s := range e.State {
		w.line("    await expectState(h, %s, %s);", dartString(s.Mapping), dartRecord(s.Record))
	}
	if len(e.Emits) > 0 {
		w.line("    await expectEmitted(h, %s);", dartStrings(e.Emits))
	}
	if e.EmitsNothing {
		w.line("    await expectEmitted(h, []);")
	}
	w.line("  });")
}

func dartAlgorithm(w *writer, a Algorithm) {
	w.line("  group(%s, () {", dartString("algorithm "+a.Name))
	for _, ex := range a.Examples {
		w.line("    test(%s, () async {", dartString(ex.Label))
		w.line("      final h = await newHarness();")
		w.line("      expectValue(await h.compute(%s, %s), %s);", dartString(a.Mapping), dartRecord(ex.Input), dartValue(ex.Expected))
		w.line("    });")
	}
	w.line("  });")
}

func dartRecord(fields []Field) string {
	var parts []string
	for _, f := range fields {
		parts = append(parts, dartString(f.Name)+": "+dartValue(f.Value))
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

func dartValue(v Value) string {
	if v.Null {
		return "Value.none"
	}
	return "const " + dartPlain(v)
}

// dartPlain is a value without const, for inside a const one.
func dartPlain(v Value) string {
	if v.Null {
		return "Value.none"
	}
	out := fmt.Sprintf("Value(%s, %s", dartString(v.Kind), dartString(v.Text))
	if len(v.Parts) > 0 {
		var parts []string
		for _, f := range v.Parts {
			parts = append(parts, dartString(f.Name)+": "+dartPlain(f.Value))
		}
		out += ", parts: {" + strings.Join(parts, ", ") + "}"
	}
	if len(v.Items) > 0 {
		var items []string
		for _, item := range v.Items {
			items = append(items, dartPlain(item))
		}
		out += ", items: [" + strings.Join(items, ", ") + "]"
	}
	return out + ")"
}

func dartStrings(list []string) string {
	var qs []string
	for _, s := range list {
		qs = append(qs, dartString(s))
	}
	return "[" + strings.Join(qs, ", ") + "]"
}

// dartString is a Dart string literal of s.
func dartString(s string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range s {
		switch {
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\'':
			b.WriteString(`\'`)
		case r == '$':
			b.WriteString(`\$`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('\'')
	return b.String()
}

// dartPrelude is the part of the Dart library that does not depend on the
// specification.
const dartPrelude = `/// A value of the design with its type, as the specification writes it:
/// text is the value's text, kind its type in the expression language
/// (int, uint, double, decimal, string, bool, enum, date, timestamp,
/// duration, time, bytes, object, list or null). An object, such as a value
/// object, has its parts in parts and a list its items in items, each with
/// its own type; text is then the value as JSON.
class Value {
  const Value(this.kind, this.text, {this.parts = const {}, this.items = const []});

  static const none = Value('null', '');

  final String kind;
  final String text;
  final Map<String, Value> parts;
  final List<Value> items;

  @override
  String toString() => kind == 'null' ? 'null' : '$kind $text';
}

/// A record or an input: values by field or parameter name.
typedef Fields = Map<String, Value>;

/// What an operation or a page answers.
class Response {
  const Response(this.status, this.body);

  final int status;
  final Fields body;
}

/// What a command run gives.
class CommandResult {
  const CommandResult(this.exit, this.output);

  final int exit;
  final List<String> output;
}

/// What the project gives the generated tests, in specarch_harness.dart
/// beside them, through ` + "`Future<Harness> newHarness()`" + `: how a caller signs
/// in, how a record is stored and read back, how an operation is called, a
/// command run, a page opened and an algorithm computed. Each name it takes
/// is the mapping the implementation file gives the element, or the
/// element's own name when it gives none. request gets the path as the
/// specification writes it, such as /loans/{loanId}/return; the harness
/// fills its parameters from the input.
abstract interface class Harness {
  Future<void> signIn(String role);
  Future<void> insert(String mapping, Fields record);
  Future<List<Fields>> records(String mapping);
  Future<Response> request(
    String mapping,
    String method,
    String path,
    Fields input,
  );
  Future<CommandResult> run(
    String mapping,
    String command,
    Map<String, List<Value>> arguments,
    Fields options,
  );
  Future<Response> open(
    String mapping,
    String page,
    String route,
    Fields input,
  );
  Future<List<String>> emitted();
  Future<Value> compute(String mapping, Fields input);
}

/// Whether a value got is the value wanted, in its type: decimals and
/// numbers by value, an object when it holds every part wanted, a list item
/// by item, everything else by text.
bool sameValue(Value a, Value b) {
  switch (a.kind) {
    case 'decimal' || 'int' || 'uint' || 'double':
      final x = _number(a.text), y = _number(b.text);
      return x != null && x == y;
    case 'object':
      return b.kind == 'object' && holds(a.parts, b.parts);
    case 'list':
      if (b.kind != 'list' || a.items.length != b.items.length) {
        return false;
      }
      for (var i = 0; i < a.items.length; i++) {
        if (!sameValue(a.items[i], b.items[i])) {
          return false;
        }
      }
      return true;
  }
  return a.kind == b.kind && a.text == b.text;
}

/// A number's text in one form, digits and a power of ten with no zero at
/// either end of the digits, so that numbers compare exactly whatever their
/// length; null when the whole text is not a number.
String? _number(String s) {
  final m = RegExp(r'^([+-]?)([0-9]+\.?[0-9]*|\.[0-9]+)([eE][+-]?[0-9]+)?$').firstMatch(s);
  if (m == null) {
    return null;
  }
  final parts = m[2]!.split('.');
  final fraction = parts.length > 1 ? parts[1] : '';
  var digits = parts[0] + fraction;
  var exponent = int.parse(m[3]?.substring(1) ?? '0') - fraction.length;
  digits = digits.replaceFirst(RegExp(r'^0+'), '');
  if (digits.isEmpty) {
    return '0';
  }
  final kept = digits.replaceFirst(RegExp(r'0+$'), '');
  exponent += digits.length - kept.length;
  return '${m[1] == '-' ? '-' : ''}${kept}e$exponent';
}

/// Whether a record has every value of want.
bool holds(Fields r, Fields want) =>
    want.entries.every((e) => r.containsKey(e.key) && sameValue(r[e.key]!, e.value));

void expectStatus(Response r, int status) {
  if (r.status != status) {
    fail('status ${r.status}, want $status');
  }
}

void expectBody(Response r, Fields want) {
  if (!holds(r.body, want)) {
    fail('body ${r.body} does not hold $want');
  }
}

void expectExit(CommandResult r, int exit) {
  if (r.exit != exit) {
    fail('exit ${r.exit}, want $exit');
  }
}

void expectOutput(CommandResult r, List<String> lines) {
  if (r.output.length != lines.length ||
      Iterable<int>.generate(lines.length)
          .any((i) => r.output[i] != lines[i])) {
    fail('output ${r.output}, want $lines');
  }
}

Future<void> expectState(Harness h, String mapping, Fields want) async {
  if (!(await h.records(mapping)).any((r) => holds(r, want))) {
    fail('no record of $mapping holds $want');
  }
}

Future<void> expectEmitted(Harness h, List<String> messages) async {
  final got = await h.emitted();
  for (final m in messages) {
    if (!got.contains(m)) {
      fail('$m was not published; published: $got');
    }
  }
  if (messages.isEmpty && got.isNotEmpty) {
    fail('nothing should be published; published: $got');
  }
}

void expectValue(Value got, Value want) {
  if (!sameValue(got, want)) {
    fail('got $got, want $want');
  }
}`
