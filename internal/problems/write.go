// Names of the two files the problems target writes.
const (
	TextName  = "problems.txt"
	SARIFName = "problems.sarif"
)

// Text is the problems file: the headline naming the specification and
// the counts, as Headline makes it in the document's language, a line
// naming where it was made from, then one line per problem, each followed
// by its notes. The problem lines are the validator's and the editors'
// format, the same in every language.
func Text(headline, relRoot string, ps []Problem) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n", headline)
	fmt.Fprintf(&b, "Generated by specarch document problems from %s. Do not edit this file: fix the specification and generate again.\n", relRoot)
	if len(ps) > 0 {
		b.WriteString("\n")
	}
	for _, p := range ps {
		b.WriteString(p.String())
		b.WriteString("\n")
		for _, n := range p.Notes {
			b.WriteString(n.String())
			b.WriteString("\n")
		}
	}
	return b.String()
}

// Tally is what the headline of the problems file counts: the errors,
// the warnings, and the open questions in all and by priority.
type Tally struct {
	Errors, Warnings, Questions int
	Must, Should, Could         int
}

// Count tallies the problems.
func Count(ps []Problem) Tally {
	var t Tally
	for _, p := range ps {
		switch p.Severity {
		case Error:
			t.Errors++
		case Warning:
			t.Warnings++
		case Question:
			t.Questions++
			switch p.Priority {
			case "must":
				t.Must++
			case "should":
				t.Should++
			case "could":
				t.Could++
			}
		}
	}
	return t
}

// The SARIF 2.1.0 log, as much of it as SpecArch writes.
type sarifLog struct {
	Schema  string     `json:"$schema"`
	Version string     `json:"version"`
	Runs    []sarifRun `json:"runs"`
}

type sarifRun struct {
	Tool       sarifTool     `json:"tool"`
	ColumnKind string        `json:"columnKind"`
	Results    []sarifResult `json:"results"`
	Properties sarifRunProps `json:"properties"`
}

// sarifRunProps is what an agent queue needs of the specification as a
// whole: the folder to run specarch decide on, relative to the log, and
// the specification's name and version (ADR-156).
type sarifRunProps struct {
	Specification string `json:"specification"`
	Title         string `json:"title"`
	Version       string `json:"version,omitempty"`
}

type sarifTool struct {
	Driver sarifDriver `json:"driver"`
}

type sarifDriver struct {
	Name           string      `json:"name"`
	InformationURI string      `json:"informationUri"`
	Rules          []sarifRule `json:"rules"`
}

type sarifRule struct {
	ID string `json:"id"`
}

type sarifMessage struct {
	Text string `json:"text"`
}

type sarifResult struct {
	RuleID              string               `json:"ruleId"`
	Kind                string               `json:"kind"`
	Level               string               `json:"level"`
	Message             sarifMessage         `json:"message"`
	Locations           []sarifLocation      `json:"locations"`
	PartialFingerprints map[string]string    `json:"partialFingerprints"`
	RelatedLocations    []sarifLocation      `json:"relatedLocations,omitempty"`
	Properties          *sarifQuestionFields `json:"properties,omitempty"`
}

type sarifLocation struct {
	ID               *int                   `json:"id,omitempty"`
	PhysicalLocation sarifPhysicalLocation  `json:"physicalLocation"`
	LogicalLocations []sarifLogicalLocation `json:"logicalLocations,omitempty"`
	Message          *sarifMessage          `json:"message,omitempty"`
}

type sarifPhysicalLocation struct {
	ArtifactLocation sarifArtifactLocation `json:"artifactLocation"`
	Region           sarifRegion           `json:"region"`
}

type sarifArtifactLocation struct {
	URI       string `json:"uri"`
	URIBaseID string `json:"uriBaseId"`
}

type sarifRegion struct {
	StartLine   int `json:"startLine"`
	StartColumn int `json:"startColumn"`
}

type sarifLogicalLocation struct {
	FullyQualifiedName string `json:"fullyQualifiedName"`
	Kind               string `json:"kind"`
}

// sarifQuestionFields are a question's own fields, the interface an agent
// queue reads (ADR-156): a key is added in a later release, never renamed
// or taken away.
type sarifQuestionFields struct {
	Question     string   `json:"question"`
	Priority     string   `json:"priority"`
	QuestionKind string   `json:"questionKind"`
	Certainty    string   `json:"certainty,omitempty"`
	DecidedBy    string   `json:"decidedBy,omitempty"`
	Options      []string `json:"options,omitempty"`
	Blocks       []string `json:"blocks"`
	Why          string   `json:"why,omitempty"`
}

// SARIF is the same problems as one SARIF 2.1.0 run. name is the
// specification's title, or its root file when it has none; version may be
// empty; relRoot is the root file relative to the folder the log is
// written in.
func SARIF(name, version, relRoot string, ps []Problem) string {
	run := sarifRun{
		Tool: sarifTool{Driver: sarifDriver{
			Name:           "specarch",
			InformationURI: "https://github.com/SpecArch/specarch",
			Rules:          []sarifRule{},
		}},
		ColumnKind: "unicodeCodePoints",
		Results:    []sarifResult{},
		Properties: sarifRunProps{Specification: path.Dir(relRoot), Title: name, Version: version},
	}
	rules := map[string]bool{}
	for _, p := range ps {
		rules[p.Rule] = true
		r := sarifResult{
			RuleID:              p.Rule,
			Kind:                "fail",
			Level:               string(p.Severity),
			Message:             sarifMessage{p.Message},
			PartialFingerprints: map[string]string{"specarchId/v1": p.ID},
		}
		if p.Severity == Question {
			r.Kind, r.Level = "open", "none"
			blocks := p.Blocks
			if blocks == nil {
				blocks = []string{}
			}
			r.Properties = &sarifQuestionFields{Question: p.Question, Priority: p.Priority, QuestionKind: p.Kind, Certainty: p.Certainty, DecidedBy: p.DecidedBy, Options: p.Options, Blocks: blocks, Why: p.Why}
		}
		r.Locations = []sarifLocation{{
			PhysicalLocation: physical(p.File, p.Line, p.Column),
			LogicalLocations: []sarifLogicalLocation{{FullyQualifiedName: p.Path, Kind: "element"}},
		}}
		for i, n := range p.Notes {
			id := i + 1
			r.RelatedLocations = append(r.RelatedLocations, sarifLocation{
				ID:               &id,
				PhysicalLocation: physical(n.File, n.Line, n.Column),
				Message:          &sarifMessage{n.Message},
			})
		}
		run.Results = append(run.Results, r)
	}
	var ids []string
	for id := range rules {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		run.Tool.Driver.Rules = append(run.Tool.Driver.Rules, sarifRule{ID: id})
	}
	log := sarifLog{
		Schema:  "https://docs.oasis-open.org/sarif/sarif/v2.1.0/errata01/os/schemas/sarif-schema-2.1.0.json",
		Version: "2.1.0",
		Runs:    []sarifRun{run},
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	_ = enc.Encode(log)
	return b.String()
}

func physical(file string, line, column int) sarifPhysicalLocation {
	return sarifPhysicalLocation{
		ArtifactLocation: sarifArtifactLocation{URI: (&url.URL{Path: file}).EscapedPath(), URIBaseID: "PROBLEMSDIR"},
		Region:           sarifRegion{StartLine: line, StartColumn: column},
	}
}
