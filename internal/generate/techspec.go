// requirements is chapter 13: the needs, the requirements with their
// attributes, and the traceability matrix: what satisfies and what
// verifies each requirement.
func requirements(d *doc, root *yaml.Node, impls []Implementation) {
	reqs := pairs(root, "requirements")
	needs := pairs(root, "needs")
	satisfied, verified := traceLinks(root, impls)
	external := map[string]bool{}
	for _, s := range pairs(root, "sources") {
		if str(s.Value, "kind") == "requirement-set" {
			external[str(s.Value, "prefix")] = true
		}
	}
	if len(reqs)+len(needs)+len(satisfied)+len(verified) == 0 {
		return
	}
	d.heading(2, "13. Requirements")
	if len(needs) > 0 {
		d.heading(3, "Needs")
		d.line("| Need | Statement | Stakeholders | Status |")
		d.line("|---|---|---|---|")
		for _, n := range needs {
			d.line("| %s | %s | %s | %s |", n.Key.Value, cell(str(n.Value, "statement")), cell(strings.Join(strs(n.Value, "stakeholders"), ", ")), cell(str(n.Value, "status")))
		}
		d.blank()
		d.explainRows(rowsOf(needs))
	}
	if len(reqs) > 0 {
		d.heading(3, "Requirements")
		d.line("| Requirement | Statement | Kind | Priority | Status | Verification | Acceptance | Needs |")
		d.line("|---|---|---|---|---|---|---|---|")
		for _, r := range reqs {
			d.line("| %s | %s | %s | %s | %s | %s | %s | %s |", r.Key.Value, cell(str(r.Value, "statement")), str(r.Value, "kind"), str(r.Value, "priority"), str(r.Value, "status"), cell(str(r.Value, "verification")), cell(strings.Join(strs(r.Value, "acceptance"), " ")), cell(strings.Join(strs(r.Value, "needs"), ", ")))
		}
		d.blank()
		d.explainRows(rowsOf(reqs))
	}
	for _, s := range pairs(root, "sources") {
		if str(s.Value, "kind") == "requirement-set" {
			d.para(fmt.Sprintf("%s: requirements with the prefix %s are in %s.", s.Key.Value, str(s.Value, "prefix"), strings.TrimSpace(str(s.Value, "title"))))
		}
	}
	d.heading(3, "Traceability")
	d.para("What satisfies and what verifies each requirement. An empty cell is a gap.")
	harm := harmColumn(reqs)
	d.line("| Requirement |%s Satisfied by | Verified by |", harm.header)
	d.line("|---|%s---|---|", harm.rule)
	ids := map[string]bool{}
	for _, r := range reqs {
		ids[r.Key.Value] = true
	}
	for k := range satisfied {
		ids[k] = true
	}
	for k := range verified {
		ids[k] = true
	}
	for _, k := range sortedLinks(ids) {
		d.line("| %s |%s %s | %s |", k, harm.cell(k), cell(strings.Join(unique(satisfied[k]), "; ")), cell(strings.Join(unique(verified[k]), "; ")))
	}
	d.blank()
}

// childLabel builds a reader's name for a nested object: "entities Loan".
func childLabel(parent, key string) string {
	if parent == "" {
		return key
	}
	return parent + " " + key
}

func unique(s []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, v := range s {
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	return out
}

// traceLinks finds, for every requirement ID, the elements that satisfy it
// and the ones that verify it, each named the way a reader finds it:
// "entities Loan", "tests loan-late".
func traceLinks(root *yaml.Node, impls []Implementation) (satisfied, verified map[string][]string) {
	satisfied = map[string][]string{}
	verified = map[string][]string{}
	var walk func(n *yaml.Node, label string)
	walk = func(n *yaml.Node, label string) {
		for _, p := range pairsOf(n) {
			switch p.Key.Value {
			case "satisfies":
				for _, r := range itemsOf(p.Value) {
					satisfied[r.Value] = append(satisfied[r.Value], label)
				}
				continue
			case "verifies":
				for _, r := range itemsOf(p.Value) {
					verified[r.Value] = append(verified[r.Value], label)
				}
				continue
			}
			walk(p.Value, childLabel(label, p.Key.Value))
		}
		for i, it := range itemsOf(n) {
			walk(it, fmt.Sprintf("%s %d", label, i+1))
		}
	}
	walk(root, "")
	for _, i := range impls {
		walk(i.Node, "implementation "+str(get(i.Node, "info"), "title"))
	}
	return satisfied, verified
}
