// Package genscripts writes the guarded operational scripts a
// specification derives: one script per operation or command that
// carries a guard and whose change the design says, by a transition it
// triggers, a PUT of the entity by its key or a DELETE by its key. Each
// script counts and locks the records the change would write and refuses
// unless their number is the guard's recordsChanged, makes the change with
// the same condition, checks the count it wrote, and commits only when the
// variable apply is true (ADR-158). A script is written for psql on
// PostgreSQL or for the mariadb client on MariaDB (ADR-167), as the
// target's dialect says. Every other guarded change is left to be written
// by hand. The tables and columns are the ones
// specarch-gen-sql writes, read through gensql.Schema, and the
// precondition is written as that generator writes a check constraint.
package genscripts

import (
	"bytes"
	"encoding/json"
	"fmt"
	"slices"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/SpecArch/specarch/internal/gensql"
	"github.com/SpecArch/specarch/internal/mark"
	"github.com/SpecArch/specarch/internal/ownership"
)

// Request is what specarch writes on a plug-in's standard input.
type Request struct {
	gensql.Request
	// Check is true when specarch only compares the output with the disk,
	// so a file built by hand is compared rather than refused.
	Check bool `json:"check"`
}

// Decode reads a request, keeping numbers as their text.
func Decode(data []byte) (*Request, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	var r Request
	if err := dec.Decode(&r); err != nil {
		return nil, err
	}
	return &r, nil
}

// The plug-in's name, as its header and its messages give it.
const name = "specarch-gen-scripts"

type gen struct {
	req     *Request
	dialect string
	spec    map[string]any
	owned   ownership.Owned
	tables  map[string]gensql.Table // by entity
	diags   []gensql.Diagnostic
	placed  map[string][]mark.Problem
	header  string
	files   []gensql.File
	names   map[string]string // a script's file name: the entry it was written for
}

// entry is one guarded operation or command.
type entry struct {
	at      string // its pointer
	id      string // the operationId, or the command's words
	what    string // "operation returnLoan" or "command backfill"
	summary string
	method  string // the HTTP method, or "" for a command
	keys    int    // its path parameters
	body    string // the entity its request body is, or ""
	guard   map[string]any
}

// change is what a script writes, derived from the entry.
type change struct {
	kind   string // "transition", "put" or "delete"
	state  gensql.Column
	to     string
	froms  []string
	sets   []gensql.Column // the columns a PUT sets from variables
	soft   gensql.Column   // the soft-delete flag, when the entity has one
	keyed  bool
	key    gensql.Column
	count  int
	cond   string // the precondition in SQL, or ""
	source string // the precondition as the specification writes it
}

// Generate writes the scripts of a request.
func Generate(r *Request) gensql.Response {
	g := &gen{req: r, spec: r.Specification, tables: map[string]gensql.Table{}, names: map[string]string{}}
	dialect := "postgresql"
	var impl gensql.Implementation
	for _, i := range r.Implementations {
		if t, ok := obj(obj0(i.Content["targets"])[r.Target]); ok || len(r.Implementations) == 1 {
			impl = i
			if d := text(t["dialect"]); d != "" {
				dialect = d
			}
			break
		}
	}
	g.owned = ownership.Of(impl.Content)
	if dialect != "postgresql" && dialect != "mariadb" {
		g.problem("error", "/", "%s writes scripts for postgresql and mariadb, and the scripts target names %s; write those scripts by hand, or generate them for postgresql or mariadb", name, dialect)
		return g.response(nil)
	}
	g.dialect = dialect
	tables, version, diags := gensql.Schema(&r.Request)
	if len(diags) > 0 {
		for _, d := range diags {
			d.Message = strings.Replace(d.Message, "specarch-gen-sql", name, 1)
			g.diags = append(g.diags, d)
		}
		return g.response(nil)
	}
	for _, t := range tables {
		g.tables[t.Entity] = t
	}
	entries := g.entries()
	g.place(entries)
	g.header = fmt.Sprintf("-- Generated by %s from %s, version %s; meta-model %s; %s through type-rendering %s. Do not edit this file: a change goes into the specification, and a change it does not derive goes into a script of your own.\n",
		name, gensql.RelRoot(r.Root, r.Output), text(obj0(g.spec["info"])["version"]), r.Specarch, dialect, version)
	if r.Draft != "" {
		g.header += "-- " + r.Draft + "\n"
	}
	g.header += g.marks(mark.File)
	for _, e := range entries {
		g.script(e)
	}
	if !r.Check && g.handWritten(r.Existing) {
		return g.response(nil)
	}
	return g.response(g.files)
}

// entries are the guarded operations in the order of the paths, then the
// guarded commands in the order of their words.
func (g *gen) entries() []entry {
	var out []entry
	paths := obj0(g.spec["paths"])
	for _, p := range sortedKeys(paths) {
		item := obj0(paths[p])
		for _, method := range []string{"get", "put", "post", "delete", "patch"} {
			op := obj0(item[method])
			guard, ok := obj(op["guard"])
			if !ok {
				continue
			}
			keys := 0
			for _, prm := range parameters(item, op) {
				if text(prm["in"]) == "path" {
					keys++
				}
			}
			id := text(op["operationId"])
			out = append(out, entry{
				at: "/paths/" + mark.Escape(p) + "/" + method, id: id, what: "operation " + id,
				summary: text(op["summary"]), method: method, keys: keys, guard: guard,
				body: entityOf(obj0(obj0(obj0(obj0(op["requestBody"])["content"])["application/json"])["schema"])),
			})
		}
	}
	commands := obj0(g.spec["commands"])
	for _, c := range sortedKeys(commands) {
		cmd := obj0(commands[c])
		if guard, ok := obj(cmd["guard"]); ok {
			out = append(out, entry{at: "/commands/" + mark.Escape(c), id: c, what: "command " + c, summary: text(cmd["summary"]), guard: guard})
		}
	}
	return out
}

// script writes the script of one guarded entry, or says why it is left
// to be written by hand.
func (g *gen) script(e entry) {
	entity := text(e.guard["entity"])
	if g.owned.Covers(ownership.Entity("entities", entity)) {
		return
	}
	at := e.at + "/guard"
	t, ok := g.tables[entity]
	if !ok {
		g.problem("warning", at, "%s guards %s, which has no table, so it has no script; its script is left to be written by hand", e.what, entity)
		return
	}
	c, why := g.derive(e, entity, t)
	if why != "" {
		g.problem("warning", at, "%s: %s; its script is left to be written by hand", e.what, why)
		return
	}
	if src := text(e.guard["precondition"]); src != "" {
		cond, err := gensql.Condition(&g.req.Request, entity, src)
		if err != "" {
			g.problem("warning", at+"/precondition", "%s: the precondition %s cannot be written in SQL: %s; its script is left to be written by hand", e.what, src, err)
			return
		}
		c.cond, c.source = cond, src
	}
	path := kebab(e.id) + ".sql"
	if other, taken := g.names[path]; taken {
		g.problem("warning", at, "%s would be written to %s, which the script of %s already is; its script is left to be written by hand", e.what, path, other)
		return
	}
	g.names[path] = e.what
	write := g.write
	if g.dialect == "mariadb" {
		write = g.writeMariaDB
	}
	g.files = append(g.files, gensql.File{Path: path, Content: g.header + g.marks(e.at) + write(e, entity, t, c, path)})
}

// derive is the change an entry makes, by keyword only, or why the
// design does not say it.
func (g *gen) derive(e entry, entity string, t gensql.Table) (change, string) {
	c := change{}
	n, err := strconv.Atoi(fmt.Sprint(e.guard["recordsChanged"]))
	if err != nil || n < 0 {
		return c, fmt.Sprintf("its recordsChanged %v is not a whole number of records", e.guard["recordsChanged"])
	}
	c.count = n
	for _, col := range t.Columns {
		if col.Role == gensql.RoleDeleted {
			c.soft = col
		}
	}
	ent := obj0(obj0(g.spec["entities"])[entity])
	var tos []string
	for _, tr := range list(ent["transitions"]) {
		tr := obj0(tr)
		if text(tr["trigger"]) != e.id {
			continue
		}
		if to := text(tr["to"]); !slices.Contains(tos, to) {
			tos = append(tos, to)
		}
		if from := text(tr["from"]); !slices.Contains(c.froms, from) {
			c.froms = append(c.froms, from)
		}
	}
	switch {
	case len(tos) > 1:
		return c, fmt.Sprintf("the transitions of %s it triggers end in %s, so which state it writes depends on more than the design says", entity, strings.Join(tos, " and "))
	case len(tos) == 1 && slices.Contains(c.froms, tos[0]):
		return c, fmt.Sprintf("it moves %s from %s to %s, so a record it changed cannot be told from one it has not, and a second run would change it again", entity, tos[0], tos[0])
	case len(tos) == 1:
		c.kind, c.to = "transition", tos[0]
		state := text(ent["stateField"])
		col, ok := column(t, state)
		if !ok {
			return c, fmt.Sprintf("the state field %s of %s is not one column of %s", state, entity, t.Name)
		}
		c.state = col
	case e.method == "put" && e.body == entity && e.keys == 1:
		c.kind = "put"
		for _, col := range t.Columns {
			if col.Key || col.Generated || col.Role != "" || col.ReadOnly {
				continue
			}
			if g.encrypted(entity, col) {
				return c, fmt.Sprintf("it sets %s, which is stored encrypted, and a script cannot encrypt the value it is given", col.Field)
			}
			c.sets = append(c.sets, col)
		}
		if len(c.sets) == 0 {
			return c, fmt.Sprintf("it sets no column a caller may set: every column of %s other than its key is read-only, generated or written by the audit", t.Name)
		}
	case e.method == "delete" && e.keys == 1:
		c.kind = "delete"
	case e.method == "post":
		return c, "a POST makes a record from the values its caller sends, which the design does not give a script"
	case e.method == "patch":
		return c, "a PATCH changes the fields its caller sends, which the design does not give a script"
	case e.method == "":
		return c, fmt.Sprintf("no transition of %s names it as its trigger, so the design does not say what it writes", entity)
	default:
		return c, fmt.Sprintf("a %s %s does not say what it writes: only a transition it triggers, a PUT of %s by one path parameter or a DELETE by one path parameter does", strings.ToUpper(e.method), keyed(e.keys), entity)
	}
	if e.keys > 1 {
		return c, fmt.Sprintf("its path has %d parameters, and a script changes a record by one key", e.keys)
	}
	if e.keys == 1 {
		k, ok := key(t)
		if !ok {
			return c, fmt.Sprintf("the key of %s is not one field, and its path gives one", entity)
		}
		if c.count != 1 {
			return c, fmt.Sprintf("it changes one %s by its key, and its recordsChanged is %d", entity, c.count)
		}
		c.keyed, c.key = true, k
	}
	return c, ""
}

// encrypted says a column holds a field stored encrypted.
func (g *gen) encrypted(entity string, col gensql.Column) bool {
	props := obj0(obj0(obj0(g.spec["entities"])[entity])["properties"])
	return text(obj0(props[col.Field])["atRest"]) == "encrypted"
}

// write is the text of one psql script under its header.
func (g *gen) write(e entry, entity string, t gensql.Table, c change, path string) string {
	var b strings.Builder
	what := e.id
	if e.summary != "" {
		what += ": " + e.summary
	}
	fmt.Fprintf(&b, "-- %s\n", strings.TrimSuffix(what, "."))
	fmt.Fprintf(&b, "-- Changes exactly %s of table %s: %s.\n", records(c.count, entity), t.Name, g.describe(c))

	// The variables: the key, the values a PUT sets, the audit columns a
	// change sets that are not a time.
	var vars []gensql.Column
	if c.keyed {
		vars = append(vars, c.key)
	}
	vars = append(vars, c.sets...)
	var audit []gensql.Column
	if c.kind != "delete" || c.soft.Name != "" {
		for _, col := range t.Columns {
			if col.Role == gensql.RoleModified {
				audit = append(audit, col)
				if !isTime(col) {
					vars = append(vars, col)
				}
			}
		}
	}
	var usage []string
	for _, v := range vars {
		if v.Nullable && !v.Key {
			usage = append(usage, fmt.Sprintf("[-v %s=...]", v.Name))
			continue
		}
		usage = append(usage, fmt.Sprintf("-v %s=...", v.Name))
	}
	fmt.Fprintf(&b, "-- Dry run: psql -v ON_ERROR_STOP=1 %s-f %s\n", strings.Join(append(usage, ""), " "), path)
	b.WriteString("-- Apply: the same with -v apply=true. Without it every check runs against the data and the change is rolled back.\n")
	if len(usage) > 0 && strings.Contains(strings.Join(usage, " "), "[") {
		b.WriteString("-- A variable in brackets may be left out: its column is set to NULL.\n")
	}
	b.WriteString("\\set ON_ERROR_STOP on\n\\set QUIET on\n")
	b.WriteString("\\if :{?apply}\n\\else\n\\set apply false\n\\endif\n")
	for _, v := range vars {
		if v.Nullable && !v.Key {
			continue
		}
		fmt.Fprintf(&b, "\\if :{?%s}\n\\else\nDO $script$ BEGIN RAISE EXCEPTION %s; END $script$;\n\\endif\n", v.Name,
			quote(fmt.Sprintf("%s: the variable %s is not set; give it as psql -v %s=<%s> (%s)", path, v.Name, v.Name, columnOf(entity, v), v.Type)))
	}
	b.WriteString("BEGIN;\nSET LOCAL specarch.apply = :'apply';\n")
	for _, v := range vars {
		if v.Nullable && !v.Key {
			fmt.Fprintf(&b, "\\if :{?%s}\nSET LOCAL specarch.%s = :'%s';\n\\endif\n", v.Name, v.Name, v.Name)
			continue
		}
		fmt.Fprintf(&b, "SET LOCAL specarch.%s = :'%s';\n", v.Name, v.Name)
	}

	where := g.where(c)
	holds := g.holds(c)
	b.WriteString("DO $script$\nDECLARE\n  found bigint;\n  changed bigint;\nBEGIN\n")
	step := 0
	next := func() int { step++; return step }
	if c.keyed && holds != "" {
		fmt.Fprintf(&b, "  -- %d. Already applied: the record already holds what the change writes.\n", next())
		fmt.Fprintf(&b, "  IF EXISTS (SELECT 1 FROM %s WHERE %s AND %s) THEN\n", t.Name, g.keyEquals(c.key), holds)
		fmt.Fprintf(&b, "    RAISE NOTICE %s, %s;\n", quote(fmt.Sprintf("%s: the %s with %s %% already holds %s; nothing to change", e.what, entity, c.key.Name, g.describeHolds(c))), keyValue(c.key))
		b.WriteString("    RETURN;\n  END IF;\n")
	}
	fmt.Fprintf(&b, "  -- %d. Precondition: exactly %s to change, locked until the end.\n", next(), records(c.count, entity))
	fmt.Fprintf(&b, "  SELECT count(*) INTO found FROM (SELECT 1 FROM %s WHERE %s FOR UPDATE) AS records;\n", t.Name, where)
	fmt.Fprintf(&b, "  IF found <> %d THEN\n", c.count)
	found := "found"
	if c.keyed {
		found += ", " + keyValue(c.key)
	}
	fmt.Fprintf(&b, "    RAISE EXCEPTION %s, %s;\n  END IF;\n", quote(fmt.Sprintf("%s: %% %s records hold %s, and the change expects exactly %d; nothing was changed", e.what, entity, g.condText(c), c.count)), found)
	fmt.Fprintf(&b, "  -- %d. The change, under the same condition.\n", next())
	switch {
	case c.kind == "delete" && c.soft.Name == "":
		fmt.Fprintf(&b, "  DELETE FROM %s\n  WHERE %s;\n", t.Name, where)
	default:
		var sets []string
		switch c.kind {
		case "transition":
			sets = append(sets, fmt.Sprintf("%s = %s", c.state.Name, quote(c.to)))
		case "put":
			for _, col := range c.sets {
				sets = append(sets, fmt.Sprintf("%s = %s", col.Name, value(col)))
			}
		case "delete":
			sets = append(sets, c.soft.Name+" = true")
		}
		for _, col := range audit {
			if isTime(col) {
				sets = append(sets, col.Name+" = now()")
			} else {
				sets = append(sets, fmt.Sprintf("%s = %s", col.Name, value(col)))
			}
		}
		fmt.Fprintf(&b, "  UPDATE %s\n  SET %s\n  WHERE %s;\n", t.Name, strings.Join(sets, ",\n      "), where)
	}
	b.WriteString("  GET DIAGNOSTICS changed = ROW_COUNT;\n")
	post := "the exact count"
	if c.keyed {
		post += ", and the record holds what was written"
	}
	fmt.Fprintf(&b, "  -- %d. Postcondition: %s.\n", next(), post)
	fmt.Fprintf(&b, "  IF changed <> %d THEN\n", c.count)
	fmt.Fprintf(&b, "    RAISE EXCEPTION %s, changed;\n  END IF;\n", quote(fmt.Sprintf("%s: the change wrote %% %s records, and exactly %d was expected; another writer may have changed them after they were counted; nothing was changed", e.what, entity, c.count)))
	if c.keyed {
		check, says := "NOT EXISTS (SELECT 1 FROM "+t.Name+" WHERE "+g.keyEquals(c.key)+" AND "+holds+")", "does not hold "+g.describeHolds(c)
		if holds == "" {
			check, says = "EXISTS (SELECT 1 FROM "+t.Name+" WHERE "+g.keyEquals(c.key)+")", "is still there"
		}
		fmt.Fprintf(&b, "  IF %s THEN\n", check)
		fmt.Fprintf(&b, "    RAISE EXCEPTION %s, %s;\n  END IF;\n", quote(fmt.Sprintf("%s: after the change the %s with %s %% %s; nothing was changed", e.what, entity, c.key.Name, says)), keyValue(c.key))
	}
	fmt.Fprintf(&b, "  -- %d. Dry run unless apply is true.\n", next())
	b.WriteString("  IF current_setting('specarch.apply')::boolean THEN\n")
	fmt.Fprintf(&b, "    RAISE NOTICE %s;\n", quote(fmt.Sprintf("%s: %s changed; committing", e.what, records(c.count, entity))))
	b.WriteString("  ELSE\n")
	fmt.Fprintf(&b, "    RAISE NOTICE %s;\n", quote(fmt.Sprintf("%s: dry run: %s would change, and every check passed; rolling back. Run it again with -v apply=true to make the change", e.what, records(c.count, entity))))
	b.WriteString("  END IF;\nEND\n$script$;\n")
	b.WriteString("\\if :apply\nCOMMIT;\n\\else\nROLLBACK;\n\\endif\n")
	return b.String()
}

// where is the condition of the records a change writes.
func (g *gen) where(c change) string {
	var parts []string
	if c.keyed {
		parts = append(parts, g.keyEquals(c.key))
	}
	if c.kind == "transition" {
		var froms []string
		for _, f := range c.froms {
			froms = append(froms, g.quote(f))
		}
		parts = append(parts, fmt.Sprintf("%s IN (%s)", c.state.Name, strings.Join(froms, ", ")))
	}
	if c.cond != "" {
		parts = append(parts, c.cond)
	}
	if c.soft.Name != "" {
		parts = append(parts, c.soft.Name+" = false")
	}
	return strings.Join(parts, "\n    AND ")
}

// holds is the condition that a record holds what the change writes, or
// "" for a delete that removes it.
func (g *gen) holds(c change) string {
	switch c.kind {
	case "transition":
		return fmt.Sprintf("%s = %s", c.state.Name, g.quote(c.to))
	case "put":
		same := "IS NOT DISTINCT FROM"
		if g.dialect == "mariadb" {
			same = "<=>"
		}
		var parts []string
		for _, col := range c.sets {
			parts = append(parts, fmt.Sprintf("%s %s %s", col.Name, same, g.value(col)))
		}
		return strings.Join(parts, " AND ")
	case "delete":
		if c.soft.Name != "" {
			return c.soft.Name + " = true"
		}
	}
	return ""
}

// describe says in words what a change writes.
func (g *gen) describe(c change) string {
	var s string
	switch c.kind {
	case "transition":
		s = fmt.Sprintf("sets %s to %s, from %s", c.state.Name, c.to, strings.Join(c.froms, " or "))
	case "put":
		var cols []string
		for _, col := range c.sets {
			cols = append(cols, col.Name)
		}
		s = "sets " + strings.Join(cols, ", ")
	case "delete":
		s = "deletes the record"
		if c.soft.Name != "" {
			s = "sets " + c.soft.Name + " to true"
		}
	}
	if c.keyed {
		s += ", by " + c.key.Name
	}
	if c.source != "" {
		s += ", where " + c.source
	}
	return s
}

// describeHolds says in words what a changed record holds.
func (g *gen) describeHolds(c change) string {
	switch c.kind {
	case "transition":
		return c.state.Name + " " + percent(c.to)
	case "delete":
		return c.soft.Name + " true"
	}
	return "the values given"
}

// condText is the condition of the records a change writes, in words.
func (g *gen) condText(c change) string {
	var parts []string
	if c.keyed {
		parts = append(parts, c.key.Name+" %")
	}
	if c.kind == "transition" {
		parts = append(parts, c.state.Name+" "+percent(strings.Join(c.froms, " or ")))
	}
	if c.source != "" {
		parts = append(parts, percent(c.source))
	}
	if c.soft.Name != "" {
		parts = append(parts, "not deleted")
	}
	if len(parts) == 0 {
		return "no condition"
	}
	return strings.Join(parts, ", ")
}

// keyEquals is the condition on a record's key.
func (g *gen) keyEquals(k gensql.Column) string { return k.Name + " = " + g.keyValue(k) }

// keyValue is a key variable's value in the target's dialect.
func (g *gen) keyValue(k gensql.Column) string {
	if g.dialect == "mariadb" {
		return mariaValue(k)
	}
	return keyValue(k)
}

// value is a variable's value as the column's type in the target's
// dialect.
func (g *gen) value(col gensql.Column) string {
	if g.dialect == "mariadb" {
		return mariaValue(col)
	}
	return value(col)
}

// quote is a SQL string literal in the target's dialect.
func (g *gen) quote(s string) string {
	if g.dialect == "mariadb" {
		return mariaQuote(s)
	}
	return quote(s)
}

// keyValue is a key variable's value, cast as value casts it and, for a
// NUMERIC or DECIMAL key, without its precision and scale as well:
// PostgreSQL rounds a value cast to numeric(p,s) to s fractional digits,
// so a key given as 123.7 would become 124 and name another record. Cast
// without them, a fractional key matches no record and the count refuses
// it. A value written to a column keeps the width, since the column rounds
// it the same way and the checks then agree with what was written.
func keyValue(k gensql.Column) string {
	base, _, sized := strings.Cut(k.Type, "(")
	switch strings.ToUpper(strings.TrimSpace(base)) {
	case "NUMERIC", "DECIMAL":
		if sized {
			return fmt.Sprintf("current_setting('specarch.%s', true)::NUMERIC", k.Name)
		}
	}
	return value(k)
}

// value is a variable's value as the column's type. A character type is
// cast without its length: PostgreSQL cuts a string cast to varchar(n) or
// char(n) to n characters without a word, and only an assignment to the
// column refuses one that is too long, so a key given too long would match
// the record named by its prefix, and a value too long would be cut.
func value(col gensql.Column) string {
	return fmt.Sprintf("current_setting('specarch.%s', true)::%s", col.Name, castType(col.Type))
}

// castType is a column's type with the length of a character type left out.
func castType(typ string) string {
	base, _, sized := strings.Cut(typ, "(")
	if !sized {
		return typ
	}
	switch strings.ToUpper(strings.TrimSpace(base)) {
	case "VARCHAR", "CHARACTER VARYING":
		return "VARCHAR"
	case "CHAR", "CHARACTER", "BPCHAR":
		return "text"
	}
	return typ
}

// isTime says an audit column holds the instant of the change, whatever
// type the dialect renders it as.
func isTime(col gensql.Column) bool { return col.Format == "date-time" }

// columnOf says which field a column holds, for the message that asks for
// its variable.
func columnOf(entity string, col gensql.Column) string {
	if col.Field != "" {
		return entity + "." + col.Field
	}
	return col.Name
}

func records(n int, entity string) string {
	if n == 1 {
		return "1 " + entity + " record"
	}
	return fmt.Sprintf("%d %s records", n, entity)
}

func keyed(keys int) string {
	switch keys {
	case 0:
		return "on a path with no parameter"
	case 1:
		return "on a path with one parameter"
	}
	return fmt.Sprintf("on a path with %d parameters", keys)
}

// quote is a SQL string literal.
func quote(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

// percent is text from the specification inside a RAISE message, which
// reads a percent sign as the place of a value and two as one sign.
func percent(s string) string { return strings.ReplaceAll(s, "%", "%%") }

// column is the column that holds a field, when it is one column.
func column(t gensql.Table, field string) (gensql.Column, bool) {
	var found []gensql.Column
	for _, c := range t.Columns {
		if c.Field == field && c.Role == "" {
			found = append(found, c)
		}
	}
	if len(found) != 1 {
		return gensql.Column{}, false
	}
	return found[0], true
}

// key is a table's primary key column, when the key is one field.
func key(t gensql.Table) (gensql.Column, bool) {
	var keys []gensql.Column
	for _, c := range t.Columns {
		if c.Key {
			keys = append(keys, c)
		}
	}
	if len(keys) != 1 {
		return gensql.Column{}, false
	}
	return keys[0], true
}

// parameters are a path item's parameters and its operation's.
func parameters(item, op map[string]any) []map[string]any {
	var out []map[string]any
	for _, l := range []any{item["parameters"], op["parameters"]} {
		for _, p := range list(l) {
			out = append(out, obj0(p))
		}
	}
	return out
}

// entityOf is the entity a schema refers to, or "".
func entityOf(schema map[string]any) string {
	if ref, ok := strings.CutPrefix(text(schema["$ref"]), "#/entities/"); ok {
		return ref
	}
	return ""
}

// kebab turns returnLoan into return-loan and "backfill cards" into
// backfill-cards.
func kebab(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				b.WriteByte('-')
			}
			r = unicode.ToLower(r)
		}
		if r == ' ' || r == '_' || r == '.' {
			r = '-'
		}
		b.WriteRune(r)
	}
	return b.String()
}

// place places the request's problems at the entries the scripts show
// (internal/mark).
func (g *gen) place(entries []entry) {
	var elements []string
	for _, e := range entries {
		elements = append(elements, e.at)
	}
	sort.Strings(elements)
	g.placed = mark.Place(g.req.Problems, elements, []string{"/paths", "/commands"})
}

// marks are the comment lines of the problems placed at an element.
func (g *gen) marks(ptr string) string {
	var b strings.Builder
	for _, p := range g.placed[ptr] {
		b.WriteString("-- " + mark.Line(p) + "\n")
	}
	return b.String()
}

// handWritten refuses to write over a file in the output folder that this
// plug-in did not write: a script written by hand is never touched.
func (g *gen) handWritten(existing []gensql.File) bool {
	have := map[string]string{}
	for _, f := range existing {
		have[f.Path] = f.Content
	}
	found := false
	for _, f := range g.files {
		if content, ok := have[f.Path]; ok && !strings.HasPrefix(content, "-- Generated by "+name+" ") {
			g.problem("error", "/", "%s is in the output folder and was not written by %s, so it is left as it is and nothing is written; compare it with generate --check, move it, or delete it to have it generated", f.Path, name)
			found = true
		}
	}
	return found
}

func (g *gen) problem(severity, path, format string, args ...any) {
	g.diags = append(g.diags, gensql.Diagnostic{File: g.req.Root, Line: 1, Severity: severity, Path: path, Rule: "generator", Message: fmt.Sprintf(format, args...)})
}

func (g *gen) response(files []gensql.File) gensql.Response {
	if files == nil {
		files = []gensql.File{}
	}
	diags := g.diags
	if diags == nil {
		diags = []gensql.Diagnostic{}
	}
	return gensql.Response{Files: files, Diagnostics: diags}
}

func obj(v any) (map[string]any, bool) {
	m, ok := v.(map[string]any)
	return m, ok
}

func obj0(v any) map[string]any {
	m, _ := v.(map[string]any)
	return m
}

func list(v any) []any {
	l, _ := v.([]any)
	return l
}

func text(v any) string {
	s, _ := v.(string)
	return s
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
