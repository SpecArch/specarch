// recordDocuments are the targets made from the records beside the
// specification rather than from the specification: never drafts, and not
// outputs of the specification in the open questions document.
var recordDocuments = map[string]bool{"changes": true, "releases": true}

// newRecordDoc starts a document made from the records, with a header that
// names the root file, its version, the records folder and the meta-model.
func newRecordDoc(target string, root *yaml.Node, relRoot string, state *State) *doc {
	d := &doc{sources: get(root, "sources"), decisions: get(root, "decisions"), questions: questionsOf(root), pointerOf: pointers(root)}
	d.line("<!-- Generated by specarch document %s from %s, version %s, and the records in %s/; meta-model %s. Do not edit this file: change the YAML and generate again. -->",
		target, relRoot, str(get(root, "info"), "version"), state.RecordsRel, str(root, "specarch"))
	d.blank()
	return d
}

// recordsOf lists the records of one kind, in ID order.
func recordsOf(state *State, kind string) []*yaml.Node {
	var out []*yaml.Node
	for _, r := range state.Records {
		if str(r, "kind") == kind {
			out = append(out, r)
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return idLess(str(out[i], "id"), str(out[j], "id")) })
	return out
}

// groupOrder places each status in the register: open first, then done,
// then closed without a change.
var groupOrder = map[string]int{
	"proposed": 0, "analysed": 0, "approved": 0, "implemented": 1, "released": 1, "rejected": 2, "withdrawn": 2,
	"reported": 0, "confirmed": 0, "fixed": 1, "not-a-defect": 2, "duplicate": 2,
}

func byGroup(rs []*yaml.Node) []*yaml.Node {
	out := append([]*yaml.Node{}, rs...)
	sort.SliceStable(out, func(i, j int) bool { return groupOrder[str(out[i], "status")] < groupOrder[str(out[j], "status")] })
	return out
}

func isOpen(r *yaml.Node) bool { return groupOrder[str(r, "status")] == 0 }

// refList writes requirement IDs plain and #/ pointers as code.
func refList(refs []string) string {
	out := make([]string, len(refs))
	for i, r := range refs {
		if strings.HasPrefix(r, "#/") {
			out[i] = "`" + r + "`"
		} else {
			out[i] = r
		}
	}
	return strings.Join(out, ", ")
}

func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" || strings.HasSuffix(s, ".") {
		return s
	}
	return s + "."
}

// Changes writes the change and defect register from the records.
func Changes(root *yaml.Node, relRoot string, state *State) string {
	d := newRecordDoc("changes", root, relRoot, state)
	info := get(root, "info")
	changes, defects := recordsOf(state, "change"), recordsOf(state, "defect")
	open := 0
	for _, r := range append(append([]*yaml.Node{}, changes...), defects...) {
		if isOpen(r) {
			open++
		}
	}
	d.line("# %s: change and defect register", str(info, "title"))
	d.blank()
	d.para(fmt.Sprintf("Version %s of the specification: %s and %s are recorded beside it, %s open. Open items come first, then the ones carried out, then the ones closed without a change. The register is made from the records in `records/changes/` and `records/defects/`: they say what was asked and decided, and the specification says what is true now.",
		str(info, "version"), countText(len(changes), "change request", "change requests"), countText(len(defects), "defect", "defects"), countText(open, "item", "items")))

	d.section("Change requests")
	if len(changes) == 0 {
		d.para("No change request is recorded.")
	} else {
		changes = byGroup(changes)
		d.line("| Change | Title | Status | Type | Urgency | Impact | Release |")
		d.line("|---|---|---|---|---|---|---|")
		for _, c := range changes {
			d.line("| %s | %s | %s | %s | %s | %s | %s |", str(c, "id"), cell(str(c, "title")), str(c, "status"), str(c, "type"), str(c, "urgency"), cell(str(c, "impact")), cell(str(c, "release")))
		}
		d.blank()
		for _, c := range changes {
			d.heading(3, str(c, "id")+": "+str(c, "title"))
			d.para(fmt.Sprintf("Raised by %s on %s, in %s. %s, %s urgency%s. Status: %s.",
				str(c, "raisedBy"), str(c, "raised"), str(c, "phase"), capitalise(str(c, "type")), str(c, "urgency"), impactText(str(c, "impact")), str(c, "status")))
			d.para(str(c, "reason"))
			affects := get(c, "affects")
			var parts []string
			for _, list := range []struct{ key, verb string }{{"adds", "adds"}, {"changes", "changes"}, {"removes", "removes"}} {
				if refs := strs(affects, list.key); len(refs) > 0 {
					parts = append(parts, list.verb+" "+refList(refs))
				}
			}
			if len(parts) > 0 {
				d.para("Affects: " + strings.Join(parts, "; ") + ".")
			}
			if dec := get(c, "decision"); dec != nil {
				d.para(fmt.Sprintf("Decision: %s by %s on %s. %s", str(dec, "outcome"), str(dec, "by"), str(dec, "date"), sentence(str(dec, "why"))))
			}
			if rel := str(c, "release"); rel != "" {
				d.para("Released in " + rel + ".")
			}
		}
	}

	d.section("Defects")
	if len(defects) == 0 {
		d.para("No defect is recorded.")
	} else {
		defects = byGroup(defects)
		d.line("| Defect | Title | Status | Severity | Found in | Violates | Test |")
		d.line("|---|---|---|---|---|---|---|")
		for _, f := range defects {
			d.line("| %s | %s | %s | %s | %s | %s | %s |", str(f, "id"), cell(str(f, "title")), str(f, "status"), str(f, "severity"), foundIn(f), cell(refList(strs(f, "violates"))), cell(str(f, "test")))
		}
		d.blank()
		for _, f := range defects {
			d.heading(3, str(f, "id")+": "+str(f, "title"))
			where := "during " + str(f, "phase")
			if env := str(f, "environment"); env != "" {
				where = "in " + str(f, "phase") + ", on the " + env + " environment"
			}
			d.para(fmt.Sprintf("Reported by %s on %s, %s. Severity %s. Status: %s.", str(f, "reportedBy"), str(f, "reported"), where, str(f, "severity"), str(f, "status")))
			var lines []string
			if v := strs(f, "violates"); len(v) > 0 {
				lines = append(lines, "Violates "+refList(v)+".")
			}
			if t := str(f, "test"); t != "" {
				lines = append(lines, "The test "+t+" shows it fixed.")
			}
			if inc := strs(f, "incidents"); len(inc) > 0 {
				lines = append(lines, "Caused "+strings.Join(inc, ", ")+".")
			}
			if dup := str(f, "duplicateOf"); dup != "" {
				lines = append(lines, "A duplicate of "+dup+".")
			}
			if ch := str(f, "change"); ch != "" {
				lines = append(lines, "Not a defect; it became the change request "+ch+".")
			}
			if rel := str(f, "release"); rel != "" {
				lines = append(lines, "Fixed in "+rel+".")
			}
			d.para(strings.Join(lines, " "))
		}
	}
	return d.String()
}

// foundIn is where a defect was found: its environment, or its phase
// when it names none.
func foundIn(f *yaml.Node) string {
	if env := str(f, "environment"); env != "" {
		return env
	}
	return str(f, "phase")
}

func impactText(impact string) string {
	if impact == "" {
		return ""
	}
	return "; impact " + impact
}

func capitalise(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// Releases writes the release notes from the records, newest first.
func Releases(root *yaml.Node, relRoot string, state *State) string {
	d := newRecordDoc("releases", root, relRoot, state)
	info := get(root, "info")
	releases := recordsOf(state, "release")
	sort.SliceStable(releases, func(i, j int) bool {
		a, _ := semver.Parse(str(releases[i], "version"))
		b, _ := semver.Parse(str(releases[j], "version"))
		return semver.Compare(a, b) > 0
	})
	byID := map[string]*yaml.Node{}
	for _, r := range state.Records {
		if k := str(r, "kind"); k == "change" || k == "defect" {
			byID[str(r, "id")] = r
		}
	}
	d.line("# %s: release notes", str(info, "title"))
	d.blank()
	d.para(fmt.Sprintf("Version %s of the specification: %s recorded beside it, newest first. Each lists what it includes, grouped as added, changed, removed and fixed, from the change and defect records in `records/`.",
		str(info, "version"), countText(len(releases), "release is", "releases are")))
	if len(releases) == 0 {
		d.para("No release is recorded.")
	}
	for _, r := range releases {
		title := str(r, "version") + ", " + str(r, "status")
		if date := str(r, "date"); date != "" {
			title += " " + date
		}
		d.heading(2, title)
		groups := map[string][]string{}
		var tracker []string
		for _, id := range strs(r, "includes") {
			x := byID[id]
			if x == nil {
				tracker = append(tracker, id)
				continue
			}
			name := id + ", " + str(x, "title")
			if str(x, "kind") == "defect" {
				groups["Fixed"] = append(groups["Fixed"], name+": violated "+refList(strs(x, "violates"))+".")
				continue
			}
			affects := get(x, "affects")
			for _, g := range []struct{ key, title string }{{"adds", "Added"}, {"changes", "Changed"}, {"removes", "Removed"}} {
				if refs := strs(affects, g.key); len(refs) > 0 {
					groups[g.title] = append(groups[g.title], name+": "+refList(refs)+".")
				}
			}
		}
		if len(groups) == 0 && len(tracker) == 0 {
			d.para("Includes no recorded change or defect.")
		}
		for _, g := range []string{"Added", "Changed", "Removed", "Fixed"} {
			if len(groups[g]) == 0 {
				continue
			}
			d.heading(3, g)
			for _, item := range groups[g] {
				d.line("- %s", item)
			}
			d.blank()
		}
		if len(tracker) > 0 {
			d.para("Also includes, kept in a tracker: " + strings.Join(tracker, ", ") + ".")
		}
		var facts []string
		if v := str(r, "specificationVersion"); v != "" {
			facts = append(facts, "Specification "+v+".")
		}
		if impls := pairs(r, "implementations"); len(impls) > 0 {
			var parts []string
			for _, p := range impls {
				parts = append(parts, p.Key.Value+" "+p.Value.Value)
			}
			facts = append(facts, "Implementations: "+strings.Join(parts, ", ")+".")
		}
		if runs := strs(r, "commissioning"); len(runs) > 0 {
			run := "run "
			if len(runs) > 1 {
				run = "runs "
			}
			facts = append(facts, "Accepted by the commissioning "+run+strings.Join(runs, ", ")+".")
		}
		if c := str(r, "commit"); c != "" {
			facts = append(facts, "Built from commit "+c+".")
		}
		d.para(strings.Join(facts, " "))
	}
	return d.String()
}
