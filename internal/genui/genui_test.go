// request builds the request specarch would send for the library lending
// example's ui target, after a change to its specification and its
// implementation file's content.
func request(t *testing.T, change func(specification, content map[string]any)) *Request {
	t.Helper()
	s := spec.Load("../../examples/library-lending/spec")
	if len(s.Problems) > 0 {
		t.Fatalf("the example does not load: %v", s.Problems)
	}
	impl := s.Implementations[0]
	root := source.Parse(impl.Data).Root
	var idioms []map[string]any
	for _, u := range validate.IdiomUses(impl.Path, root, s) {
		i := map[string]any{"name": u.Name, "version": u.Version, "as": u.As}
		if u.As == "shipped" {
			i["content"] = source.ValueOf(validate.ShippedIdioms()[u.Name].Root)
		}
		idioms = append(idioms, i)
	}
	content := source.ValueOf(root).(map[string]any)
	specification := s.Value.(map[string]any)
	change(specification, content)
	data, err := json.Marshal(map[string]any{"specarch": "0.3", "target": "ui", "root": filepath.ToSlash(s.RootFile),
		"specification": specification, "output": "../../examples/library-lending/web",
		"implementations": []any{map[string]any{"file": impl.Path, "content": content, "idioms": idioms}}})
	if err != nil {
		t.Fatal(err)
	}
	r, err := Decode(data)
	if err != nil {
		t.Fatal(err)
	}
	return r
}

// unmarked is a generated file without its draft notice and marks, which
// specarch's request carries and this test's request does not.
func unmarked(content string) string {
	var out []string
	for _, l := range strings.SplitAfter(content, "\n") {
		text := strings.TrimLeft(l, "/*<!- ")
		if !strings.HasPrefix(text, "Draft: ") && !strings.HasPrefix(text, "specarch-problem: ") {
			out = append(out, l)
		}
	}
	return strings.Join(out, "")
}

// TestExample checks the generator writes exactly the screens committed in
// the example, the first of which was written by hand before it, but for
// the draft notice and the marks.
func TestExample(t *testing.T) {
	resp := Generate(request(t, func(map[string]any, map[string]any) {}))
	for _, d := range resp.Diagnostics {
		if d.Severity == "error" {
			t.Fatalf("diagnostics: %v", resp.Diagnostics)
		}
	}
	entries, err := os.ReadDir("../../examples/library-lending/web")
	if err != nil {
		t.Fatal(err)
	}
	committed := 0
	for _, e := range entries {
		if !e.IsDir() {
			committed++
		}
	}
	if len(resp.Files) != committed {
		t.Fatalf("want the %d files the example holds, got %d", committed, len(resp.Files))
	}
	for _, f := range resp.Files {
		want, err := os.ReadFile(filepath.Join("../../examples/library-lending/web", f.Path))
		if err != nil {
			t.Fatal(err)
		}
		if f.Content != unmarked(string(want)) {
			t.Errorf("%s differs from the example's", f.Path)
		}
	}
}

// withoutHeader is a generated file without its header, a page without
// its menu, whose entries come in the order of their names, and a module's
// opening comment as one line, since the generator wraps it at its own
// width.
func withoutHeader(content string) string {
	var out []string
	inMenu, opening := false, true
	for _, l := range strings.SplitAfter(unmarked(content), "\n") {
		switch {
		case strings.HasPrefix(l, "// Generated by ") || strings.HasPrefix(l, "<!-- Generated by "):
		case strings.HasPrefix(l, `<nav id="menu"`):
			inMenu = true
		case inMenu:
			inMenu = l != "</nav>\n"
		case opening && strings.HasPrefix(l, "// The page "):
			out = append(out, strings.TrimSuffix(l, "\n"))
		case opening && strings.HasPrefix(l, "// ") && len(out) > 0:
			out[len(out)-1] += " " + strings.TrimSuffix(strings.TrimPrefix(l, "// "), "\n")
		default:
			if opening && len(out) > 0 && strings.HasPrefix(out[len(out)-1], "// The page ") {
				out[len(out)-1] += "\n"
			}
			opening = false
			out = append(out, l)
		}
	}
	return strings.Join(out, "")
}

// TestReference checks the generator writes the screens written by hand
// in examples/library-lending/web/reference/ before it wrote views and
// forms, but for the header, the order of the menu's entries and the
// wrapping of a module's opening comment. form.js has moved on from the
// one written by hand: a success's page also takes its parameters from
// the record loaded and the page's own address, as the member's loans
// form needs. The modules have moved on too: every call goes through
// transport.js and names its operation's path with the {parameters} left
// in (ADR-164), so the pages' modules and view.js are not compared.
func TestReference(t *testing.T) {
	resp := Generate(request(t, func(map[string]any, map[string]any) {}))
	got := map[string]string{}
	for _, f := range resp.Files {
		got[f.Path] = f.Content
	}
	for _, name := range []string{"member-view.html", "member-form.html", "ask.js"} {
		want, err := os.ReadFile(filepath.Join("../../examples/library-lending/web/reference", name))
		if err != nil {
			t.Fatal(err)
		}
		if withoutHeader(got[name]) != withoutHeader(string(want)) {
			t.Errorf("%s differs from the one written by hand", name)
		}
	}
}

// TestRefusals refuses a target that is not plain JavaScript for the web
// and a target without a language, with no file, and reports a filter its
// list cannot ask for, a list that does not page, a list read in a
// handshake's envelope from a service in the standard dialect and one in
// an envelope that is not dxlib's as errors
// with the files still written, so specarch can mark them there.
func TestRefusals(t *testing.T) {
	ui := func(content map[string]any) map[string]any {
		return content["targets"].(map[string]any)["ui"].(map[string]any)
	}
	for _, c := range []struct {
		name   string
		change func(specification, content map[string]any)
		want   string
	}{
		{"framework", func(_, c map[string]any) { ui(c)["framework"] = "react" }, "plain-javascript only"},
		{"language", func(_, c map[string]any) { delete(ui(c)["settings"].(map[string]any), "language") }, "name no language"},
		{"filter", func(s, _ map[string]any) {
			pg := s["pages"].(map[string]any)["loans-list"].(map[string]any)
			pg["filters"] = []any{"dueOn"}
		}, "dueOn, which is neither a query parameter of listLoans"},
		{"paging", func(s, _ map[string]any) {
			get := s["paths"].(map[string]any)["/loans"].(map[string]any)["get"].(map[string]any)
			delete(get, "listOf")
		}, "listLoans has no listOf, so it does not page"},
		{"handshake", func(s, _ map[string]any) {
			s["handshakes"] = map[string]any{"preKey": map[string]any{"keyAgreement": "x25519", "signature": "ed25519", "cipher": "aes-256-cbc", "establishedBy": "listBooks"}}
			get := s["paths"].(map[string]any)["/loans"].(map[string]any)["get"].(map[string]any)
			get["handshake"] = "preKey"
		}, "listLoans, which travels in the envelope of handshake preKey, and specarch-gen-ui seals an envelope in the dxlib dialect only"},
		{"primitives", func(s, _ map[string]any) {
			s["handshakes"] = map[string]any{"preKey": map[string]any{"keyAgreement": "x25519", "signature": "ed25519", "cipher": "aes-256-gcm", "establishedBy": "listBooks"}}
			get := s["paths"].(map[string]any)["/loans"].(map[string]any)["get"].(map[string]any)
			get["handshake"] = "preKey"
		}, "whose cipher aes-256-gcm is not dxlib's envelope"},
	} {
		req := request(t, c.change)
		if c.name == "primitives" {
			req.APIDialect = "dxlib" // another implementation file's openapi target names it
		}
		resp := Generate(req)
		found := false
		for _, d := range resp.Diagnostics {
			found = found || d.Severity == "error" && strings.Contains(d.Message, c.want)
		}
		page := c.name == "filter" || c.name == "paging" || c.name == "handshake" || c.name == "primitives"
		written := map[string]bool{}
		for _, f := range resp.Files {
			written[f.Path] = true
		}
		switch {
		case !found:
			t.Errorf("%s: want an error with %q, got %v", c.name, c.want, resp.Diagnostics)
		case !page && len(resp.Files) != 0:
			t.Errorf("%s: want no file, got %d", c.name, len(resp.Files))
		case page && (!written["events.js"] || !written["members-list.html"]):
			t.Errorf("%s: want the files written, got %v", c.name, written)
		}
	}
}

// TestOwned checks that a page another stakeholder owns gets no files,
// while the other pages are written as before.
func TestOwned(t *testing.T) {
	resp := Generate(request(t, func(_, content map[string]any) {
		mappings, _ := content["mappings"].(map[string]any)
		if mappings == nil {
			mappings = map[string]any{}
			content["mappings"] = mappings
		}
		mappings["#/pages/loans-list"] = map[string]any{"target": "the circulation team's screen", "ownedBy": "librarian"}
	}))
	var paths []string
	for _, f := range resp.Files {
		paths = append(paths, f.Path)
	}
	got := strings.Join(paths, " ")
	if strings.Contains(got, "loans-list") || !strings.Contains(got, "members-list.html") {
		t.Errorf("want the members list without the owned loans list, got %s and %v", got, resp.Diagnostics)
	}
}

// TestSignInAction checks that an action whose then leaves for the
// identity provider's sign-in is written so, on a list and on a view, and
// that identity-provider.js is written with the callback's path (ADR-182).
func TestSignInAction(t *testing.T) {
	resp := Generate(request(t, func(s, _ map[string]any) {
		s["signIn"] = map[string]any{"kind": "oidc", "provider": "feeLedger", "client": "lending-desk", "flow": "authorizationCode", "pkce": true, "callback": "listBooks", "identityToken": "access"}
		for _, name := range []string{"loans-list", "member-view"} {
			for _, a := range s["pages"].(map[string]any)[name].(map[string]any)["actions"].([]any) {
				if am := a.(map[string]any); am["kind"] == "operation" {
					am["then"] = map[string]any{"navigate": "signIn"}
				}
			}
		}
	}))
	files := map[string]string{}
	for _, f := range resp.Files {
		files[f.Path] = f.Content
	}
	for _, d := range resp.Diagnostics {
		if d.Severity == "error" {
			t.Errorf("unexpected error: %s at %s", d.Message, d.Path)
		}
	}
	if !strings.Contains(files["identity-provider.js"], `const CALLBACK = "/books";`) {
		t.Errorf("identity-provider.js does not name the callback's path /books:\n%s", files["identity-provider.js"])
	}
	for _, name := range []string{"loans-list.js", "member-view.js"} {
		if !strings.Contains(files[name], "signIn: true,") {
			t.Errorf("%s does not mark its actions as leaving for the sign-in", name)
		}
	}
}
