// GoFile is the one file the Go plug-in writes in the target's folder.
const GoFile = "specarch_design_test.go"

// GenerateGo writes the Go tests of a request: one file, in the package
// the target's settings name or specarchtests.
func GenerateGo(r *Request) Response {
	s := Build(r)
	pkg := setting(r, "package")
	if pkg == "" {
		pkg = "specarchtests"
	}
	w := &writer{}
	w.line("// Code generated by specarch-gen-tests-go from %s, version %s, meta-model %s, digest %s. DO NOT EDIT.", s.Root, s.Version, s.Meta, s.Digest)
	w.head(s, true)
	w.line("")
	w.line("// Package %s runs the design tests and worked examples of %s through", pkg, s.Title)
	w.line("// the Harness the project gives them in newHarness.")
	w.line("package %s", pkg)
	w.line("")
	w.line(`import (`)
	w.line(`	"math/big"`)
	w.line(`	"testing"`)
	w.line(`)`)
	w.line("")
	w.b.WriteString(goPrelude + "\n")
	for _, t := range s.Tests {
		w.marks(s, "/tests/"+mark.Escape(t.Name), "")
		goTest(w, t)
	}
	for _, a := range s.Algorithms {
		w.marks(s, "/algorithms/"+mark.Escape(a.Name), "")
		goAlgorithm(w, a)
	}
	if len(s.Mappings) > 0 {
		w.b.WriteString(goMappingPrelude + "\n")
	}
	for _, m := range s.Mappings {
		goMapping(w, m)
	}
	in := BuildIntegration(r)
	if in.Any() {
		w.b.WriteString(goIntegrationPrelude + "\n")
		for _, u := range in.Unwritten {
			w.line("// The call %s at %s is not written: %s.", u.Reference, u.Place, u.Reason)
		}
	}
	files := []File{{Path: GoFile, Content: w.b.String()}}
	for _, m := range in.Modules {
		files = append(files, File{Path: GoIntegrationFile(m.Module), Content: goIntegration(s, in, m, pkg)})
	}
	for i, f := range files {
		src, err := format.Source([]byte(f.Content))
		if err != nil {
			return failed(r, fmt.Sprintf("the generated Go of %s does not parse (%v); this is a bug in specarch-gen-tests-go", f.Path, err))
		}
		files[i].Content = string(src)
	}
	return Response{Files: files, Diagnostics: []Diagnostic{}}
}

// GoIntegrationFile is the file of the integration tests of the calls
// into one module (ADR-226).
func GoIntegrationFile(module string) string {
	return "specarch_integration_" + snake(module) + "_test.go"
}

// goIntegration writes the integration tests of the calls into one
// module: one test per call, one subtest per path.
func goIntegration(s Suite, in Integration, m ModuleCalls, pkg string) string {
	w := &writer{}
	w.line("// Code generated by specarch-gen-tests-go from %s, version %s, meta-model %s, digest %s. DO NOT EDIT.", s.Root, s.Version, s.Meta, s.Digest)
	if s.Draft != "" {
		w.line("// %s", s.Draft)
	}
	w.line("")
	w.line("// The integration tests of the calls %s %s makes into %s %s, through", in.Caller, in.CallerVersion, m.Module, m.Version)
	w.line("// the IntegrationHarness the project gives them in newIntegrationHarness.")
	w.line("package %s", pkg)
	w.line("")
	w.line(`import "testing"`)
	w.line("")
	for _, c := range m.Calls {
		fn := "TestCall" + pascal(c.Name)
		timeout := c.Timeout
		if timeout == "" {
			timeout = "no time limit"
		}
		w.line("// %s: %s %s calls %s of %s %s, %s %s, through the dependency %s, within %s.", fn, in.Caller, in.CallerVersion, c.Operation, c.Module, c.Version, c.Method, c.Path, c.Dependency, timeout)
		w.line("// specarch: %s", c.Pointer)
		w.line("// Called from %s.", strings.Join(c.Places, ", "))
		w.line("func %s(t *testing.T) {", fn)
		var places []string
		for _, p := range c.Places {
			places = append(places, strconv.Quote(p))
		}
		w.line("	c := ModuleCall{Caller: %q, CallerVersion: %q, Dependency: %q, Module: %q, Version: %q, Operation: %q, Method: %q, Path: %q, Timeout: %q, Places: []string{%s}}",
			in.Caller, in.CallerVersion, c.Dependency, c.Module, c.Version, c.Operation, c.Method, c.Path, c.Timeout, strings.Join(places, ", "))
		if c.InputFrom != "" {
			w.line("	in := %s // from %s", goRecord(c.Input), c.InputFrom)
		} else {
			w.line("	in := Record{} // %s gives no golden input for %s; the harness fills every value the contract requires", c.Module, c.Operation)
		}
		holding := "nil"
		if c.Permission != "" {
			holding = fmt.Sprintf("[]string{%q}", c.Permission)
		}
		for _, p := range c.Paths {
			w.line("	t.Run(%q, func(t *testing.T) {", p.Name)
			w.line("		defer failedAt(t, %q)", c.Pointer)
			w.line("		h := newIntegrationHarness(t)")
			if p.Arrange != "" {
				w.line("		h.Arrange(t, c, %s)", p.Arrange)
			}
			if p.Break != "" {
				w.line("		h.Break(t, c, %q)", p.Break)
			}
			req := "Input: in"
			if p.Holding && c.Permission != "" {
				req = "Holding: " + holding + ", " + req
			}
			if p.Omit != "" {
				req += fmt.Sprintf(", Omit: %q", p.Omit)
			}
			w.line("		got := h.Call(t, c, CallRequest{%s})", req)
			switch p.Expect {
			case "status":
				w.line("		expectAnswer(t, got, %s)", p.Status)
			case "answered":
				w.line("		expectAnswered(t, got)")
			case "refused":
				w.line("		expectRefused(t, got)")
			case "failed":
				w.line("		expectFailed(t, got)")
			case "late":
				w.line("		expectGaveUp(t, got)")
			}
			if len(p.Fields) > 0 {
				var qs []string
				for _, f := range p.Fields {
					qs = append(qs, strconv.Quote(f))
				}
				w.line("		expectAnswerFields(t, got, %s)", strings.Join(qs, ", "))
			}
			w.line("	})")
		}
		w.line("}")
		w.line("")
	}
	return w.b.String()
}

func goTest(w *writer, t Test) {
	fn := "Test" + pascal(t.Name)
	if t.NotApplicable != "" {
		w.line("// %s is not applicable: %s", t.Name, t.NotApplicable)
		w.line("")
		return
	}
	w.line("// %s: %s, %s scenario.", fn, t.Subject, t.Scenario)
	w.line("// specarch: #/tests/%s", mark.Escape(t.Name))
	w.line("func %s(t *testing.T) {", fn)
	w.line("	defer failedAt(t, %q)", "#/tests/"+mark.Escape(t.Name))
	w.line("	// Given %s", t.Given)
	w.line("	// When %s", t.When)
	w.line("	// Then %s", t.Then)
	w.line("	h := newHarness(t)")
	if t.Caller != "" {
		w.line("	h.SignIn(t, %q)", t.Caller)
	}
	for _, s := range t.Inserts {
		w.line("	h.Insert(t, %q, %s)", s.Mapping, goRecord(s.Record))
	}
	c := t.Call
	if c == nil {
		w.line("	body%s(t, h) // written by hand beside this file: %s", pascal(t.Name), t.NoCall)
		w.line("}")
		w.line("")
		return
	}
	if note := c.TransportNote(); note != "" {
		w.line("	// %s", note)
	}
	switch c.Kind {
	case "request":
		w.line("	got := h.Request(t, %q, %q, %q, %s)", c.Mapping, c.Method, c.Path, goRecord(c.Input))
	case "run":
		var parts []string
		for _, a := range c.Arguments {
			var vs []string
			for _, v := range a.Values {
				vs = append(vs, goValue(v))
			}
			parts = append(parts, fmt.Sprintf("%q: {%s}", a.Name, strings.Join(vs, ", ")))
		}
		w.line("	got := h.Run(t, %q, %q, map[string][]Value{%s}, %s)", c.Mapping, c.Command, strings.Join(parts, ", "), goRecord(c.Options))
	case "open":
		w.line("	got := h.Open(t, %q, %q, %q, %s)", c.Mapping, c.Page, c.Route, goRecord(c.Input))
	}
	e := t.Expect
	if e.Status != "" {
		w.line("	expectStatus(t, got, %s)", e.Status)
	}
	if e.HasBody {
		w.line("	expectBody(t, got, %s)", goRecord(e.Body))
	}
	if e.Exit != "" {
		w.line("	expectExit(t, got, %s)", e.Exit)
	}
	if e.HasOutput {
		var qs []string
		for _, l := range e.Output {
			qs = append(qs, strconv.Quote(l))
		}
		w.line("	expectOutput(t, got, []string{%s})", strings.Join(qs, ", "))
	}
	for _, s := range e.State {
		w.line("	expectState(t, h, %q, %s)", s.Mapping, goRecord(s.Record))
	}
	if len(e.Emits) > 0 {
		var qs []string
		for _, m := range e.Emits {
			qs = append(qs, strconv.Quote(m))
		}
		w.line("	expectEmitted(t, h, %s)", strings.Join(qs, ", "))
	}
	if e.EmitsNothing {
		w.line("	expectEmitted(t, h)")
	}
	if !e.Checked() {
		w.line("	_ = got")
	}
	w.line("}")
	w.line("")
}

func goAlgorithm(w *writer, a Algorithm) {
	fn := "TestAlgorithm" + pascal(a.Name)
	w.line("// %s runs the worked examples of algorithm %s.", fn, a.Name)
	w.line("func %s(t *testing.T) {", fn)
	w.line("	h := newHarness(t)")
	for _, ex := range a.Examples {
		w.line("	t.Run(%q, func(t *testing.T) {", ex.Label)
		w.line("		expectValue(t, h.Compute(t, %q, %s), %s)", a.Mapping, goRecord(ex.Input), goValue(ex.Expected))
		w.line("	})")
	}
	w.line("}")
	w.line("")
}

func goMapping(w *writer, m Mapping) {
	fn := "TestMapping" + pascal(m.Operation) + pascal(m.Call)
	w.line("// %s runs the worked examples of the mapping of %s's call to %s.", fn, m.Operation, m.Call)
	w.line("func %s(t *testing.T) {", fn)
	w.line("	h := mappingHarness(t, newHarness(t))")
	for _, ex := range m.Examples {
		w.line("	t.Run(%q, func(t *testing.T) {", ex.Label)
		if ex.HasSent {
			w.line("		expectRecord(t, h.Send(t, %q, %q, %s), %s)", m.Mapping, m.Reference, goRecord(ex.Input), goRecord(ex.Sent))
		}
		if ex.HasKept {
			w.line("		expectRecord(t, h.Receive(t, %q, %q, %s), %s)", m.Mapping, m.Reference, goRecord(ex.Answer), goRecord(ex.Kept))
		}
		w.line("	})")
	}
	w.line("}")
	w.line("")
}

func goRecord(fields []Field) string {
	if len(fields) == 0 {
		return "Record{}"
	}
	var parts []string
	for _, f := range fields {
		parts = append(parts, fmt.Sprintf("%q: %s", f.Name, goValue(f.Value)))
	}
	return "Record{" + strings.Join(parts, ", ") + "}"
}

func goValue(v Value) string {
	if v.Null {
		return `Value{Kind: "null"}`
	}
	out := fmt.Sprintf("Value{Kind: %q, Text: %q", v.Kind, v.Text)
	if len(v.Parts) > 0 {
		out += ", Parts: " + goRecord(v.Parts)
	}
	if len(v.Items) > 0 {
		var items []string
		for _, item := range v.Items {
			items = append(items, goValue(item))
		}
		out += ", Items: []Value{" + strings.Join(items, ", ") + "}"
	}
	return out + "}"
}

// goMappingPrelude is the part of a generated file whose specification
// has mapping examples: the harness they need beside Harness, so a
// project without them is not asked for it (ADR-207).
const goMappingPrelude = `// MappingHarness is what the project's harness gives beside Harness when
// the specification has worked examples of a call's mapping: Send, what the
// implementation sends for an operation's call from our values, and
// Receive, what it keeps in the record from their answer. mapping is the
// operation's, as Request takes it; call is the calls entry's call, such
// as feeLedger#/operations/postCharge.
type MappingHarness interface {
	Send(t *testing.T, mapping, call string, in Record) Record
	Receive(t *testing.T, mapping, call string, answer Record) Record
}

// mappingHarness is the harness as a MappingHarness, or a failed test
// naming what to add.
func mappingHarness(t *testing.T, h Harness) MappingHarness {
	t.Helper()
	m, ok := h.(MappingHarness)
	if !ok {
		t.Fatalf("the harness newHarness gives has no Send and Receive, which the mapping examples need; add them as MappingHarness declares")
	}
	return m
}

func expectRecord(t *testing.T, got, want Record) {
	t.Helper()
	if !holds(got, want) {
		t.Errorf("record %v does not hold %v", got, want)
	}
}
`

// goIntegrationPrelude is the part of the design tests' file whose
// specification calls another module: what the integration tests share,
// so the file of each module's calls holds that module's tests alone
// (ADR-226).
const goIntegrationPrelude = `// ModuleCall is one call into another module of the estate, as the
// calling module's design makes it: the two modules with their versions,
// the dependency, the called operation, its method and path as the called
// module writes them, the calling module's time limit for the dependency
// (ISO 8601, "" for none) and the places of the calling design that make it.
type ModuleCall struct {
	Caller, CallerVersion string
	Dependency            string
	Module, Version       string
	Operation             string
	Method, Path          string
	Timeout               string
	Places                []string
}

// CallRequest is what one path of a call sends: the permissions the
// caller holds, none for a denied call; the values the design gives, the
// harness filling every other value the called contract requires; and a
// required field to leave out of the request, "" for none.
type CallRequest struct {
	Holding []string
	Input   Record
	Omit    string
}

// Answer is what the call gave the caller: the status and body the called
// module answered, Failed when no answer the caller could read came, and
// TimedOut when the caller gave up at its time limit.
type Answer struct {
	Status   int
	Body     Value
	Failed   bool
	TimedOut bool
}

// IntegrationHarness is what the project gives the integration tests, in a
// file of its own, through func newIntegrationHarness(t *testing.T)
// IntegrationHarness: Call makes the call as the calling module makes it,
// through its own client, to a running instance of the called module, as
// a caller holding the permissions given; Arrange puts the called module in
// a state in which the call answers status; Break makes it fail ("fails")
// or answer later than the time limit ("times out") for the calls after.
type IntegrationHarness interface {
	Call(t *testing.T, c ModuleCall, r CallRequest) Answer
	Arrange(t *testing.T, c ModuleCall, status int)
	Break(t *testing.T, c ModuleCall, how string)
}

func expectAnswer(t *testing.T, a Answer, status int) {
	t.Helper()
	if a.Failed || a.TimedOut || a.Status != status {
		t.Errorf("answer %d (failed %v, timed out %v), want %d", a.Status, a.Failed, a.TimedOut, status)
	}
}

func expectAnswered(t *testing.T, a Answer) {
	t.Helper()
	if a.Failed || a.TimedOut || a.Status < 200 || a.Status > 299 {
		t.Errorf("answer %d (failed %v, timed out %v), want a success", a.Status, a.Failed, a.TimedOut)
	}
}

func expectRefused(t *testing.T, a Answer) {
	t.Helper()
	if a.Failed || a.TimedOut || a.Status < 400 || a.Status > 499 {
		t.Errorf("answer %d (failed %v, timed out %v), want a refusal", a.Status, a.Failed, a.TimedOut)
	}
}

func expectFailed(t *testing.T, a Answer) {
	t.Helper()
	if !a.Failed && a.Status < 500 {
		t.Errorf("answer %d, want the call to fail", a.Status)
	}
}

func expectGaveUp(t *testing.T, a Answer) {
	t.Helper()
	if !a.TimedOut {
		t.Errorf("answer %d (failed %v), want the caller to give up at its time limit", a.Status, a.Failed)
	}
}

// expectAnswerFields checks that the answer's body holds every field
// named: the object answered, or each record of a list.
func expectAnswerFields(t *testing.T, a Answer, fields ...string) {
	t.Helper()
	records := []Record{a.Body.Parts}
	if a.Body.Kind == "list" {
		records = nil
		for _, item := range a.Body.Items {
			records = append(records, item.Parts)
		}
	}
	for i, r := range records {
		for _, f := range fields {
			if _, ok := r[f]; !ok {
				t.Errorf("record %d of the answer has no %s", i, f)
			}
		}
	}
}
`

// goPrelude is the part of every generated file that does not depend on the
// specification: the values, the harness and the checks.
const goPrelude = `// Value is a value of the design with its type, as the specification
// writes it: Text is the value's text, Kind its type in the expression
// language (int, uint, double, decimal, string, bool, enum, date,
// timestamp, duration, time, bytes, object, list or null). An object, such
// as a value object, has its parts in Parts and a list its items in Items,
// each with its own type; Text is then the value as JSON.
type Value struct {
	Kind  string
	Text  string
	Parts Record
	Items []Value
}

// Record is a record or an input: values by field or parameter name.
type Record map[string]Value

// Response is what an operation or a page answers.
type Response struct {
	Status int
	Body   Record
}

// Result is what a command run gives.
type Result struct {
	Exit   int
	Output []string
}

// Harness is what the project gives the generated tests, in a file of its
// own beside this one, through func newHarness(t *testing.T) Harness: how
// a caller signs in, how a record is stored and read back, how an operation is
// called, a command run, a page opened and an algorithm computed. Each
// name it takes is the mapping the implementation file gives the element,
// or the element's own name when it gives none. Request gets the path as
// the specification writes it, such as /loans/{loanId}/return; the harness
// fills its parameters from the input record.
type Harness interface {
	SignIn(t *testing.T, role string)
	Insert(t *testing.T, mapping string, r Record)
	Records(t *testing.T, mapping string) []Record
	Request(t *testing.T, mapping, method, path string, in Record) Response
	Run(t *testing.T, mapping, command string, arguments map[string][]Value, options Record) Result
	Open(t *testing.T, mapping, page, route string, in Record) Response
	Emitted(t *testing.T) []string
	Compute(t *testing.T, mapping string, in Record) Value
}

// same reports whether a value got is the value wanted, in its type:
// decimals and numbers by value, an object when it holds every part wanted,
// a list item by item, everything else by text.
func same(a, b Value) bool {
	switch a.Kind {
	case "decimal", "int", "uint", "double":
		x, okx := new(big.Rat).SetString(a.Text)
		y, oky := new(big.Rat).SetString(b.Text)
		return okx && oky && x.Cmp(y) == 0
	case "object":
		return b.Kind == "object" && holds(a.Parts, b.Parts)
	case "list":
		if b.Kind != "list" || len(a.Items) != len(b.Items) {
			return false
		}
		for i := range a.Items {
			if !same(a.Items[i], b.Items[i]) {
				return false
			}
		}
		return true
	}
	return a.Kind == b.Kind && a.Text == b.Text
}

// holds reports whether a record has every value of want.
func holds(r, want Record) bool {
	for k, v := range want {
		if got, ok := r[k]; !ok || !same(got, v) {
			return false
		}
	}
	return true
}

func expectStatus(t *testing.T, r Response, status int) {
	t.Helper()
	if r.Status != status {
		t.Errorf("status %d, want %d", r.Status, status)
	}
}

func expectBody(t *testing.T, r Response, want Record) {
	t.Helper()
	if !holds(r.Body, want) {
		t.Errorf("body %v does not hold %v", r.Body, want)
	}
}

func expectExit(t *testing.T, r Result, exit int) {
	t.Helper()
	if r.Exit != exit {
		t.Errorf("exit %d, want %d", r.Exit, exit)
	}
}

func expectOutput(t *testing.T, r Result, lines []string) {
	t.Helper()
	if len(r.Output) != len(lines) {
		t.Errorf("output %q, want %q", r.Output, lines)
		return
	}
	for i := range lines {
		if r.Output[i] != lines[i] {
			t.Errorf("output %q, want %q", r.Output, lines)
			return
		}
	}
}

func expectState(t *testing.T, h Harness, mapping string, want Record) {
	t.Helper()
	for _, r := range h.Records(t, mapping) {
		if holds(r, want) {
			return
		}
	}
	t.Errorf("no record of %s holds %v", mapping, want)
}

func expectEmitted(t *testing.T, h Harness, messages ...string) {
	t.Helper()
	got := h.Emitted(t)
	for _, m := range messages {
		found := false
		for _, g := range got {
			found = found || g == m
		}
		if !found {
			t.Errorf("%s was not published; published: %v", m, got)
		}
	}
	if len(messages) == 0 && len(got) > 0 {
		t.Errorf("nothing should be published; published: %v", got)
	}
}

// failedAt names, under a failure, the element of the specification the
// test is about, so a remark on the failure can name it (specarch trace).
func failedAt(t *testing.T, pointer string) {
	t.Helper()
	if t.Failed() {
		t.Logf("specarch: %s", pointer)
	}
}

func expectValue(t *testing.T, got, want Value) {
	t.Helper()
	if !same(got, want) {
		t.Errorf("got %s %s, want %s %s", got.Kind, got.Text, want.Kind, want.Text)
	}
}`
